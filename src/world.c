/* bilinear height lookup on the eroded grid, for the sun ray-march */
float sample_height(float x, float z) {
    float gx = (x + TERRAIN_WORLD * 0.5f) / CELL;
    float gz = (z + TERRAIN_WORLD * 0.5f) / CELL;
    int x0 = (int)floorf(gx), z0 = (int)floorf(gz);
    if (x0 < 0 || z0 < 0 || x0 >= N - 1 || z0 >= N - 1) return -1e9f;
    float fx = gx - x0, fz = gz - z0;
    float h00 = heights[z0 * N + x0], h10 = heights[z0 * N + x0 + 1];
    float h01 = heights[(z0 + 1) * N + x0], h11 = heights[(z0 + 1) * N + x0 + 1];
    return (h00 * (1 - fx) + h10 * fx) * (1 - fz) + (h01 * (1 - fx) + h11 * fx) * fz;
}

/* How high the terrain rises in each of the eight azimuth sectors, and how
   much of the sun that leaves. Trees go in as well -- a crown is an occluder,
   and that is what gives the forest floor its shade and each trunk its
   shadow. The per-point version is horizon_at; these are the pieces. */
void sun_angles(float hours, float *az, float *elev);
void horizon_at(float x, float z, float y, int with_trees, float *out);
float surface_height(float x, float z);
float shadow_lit(const float *h, float az, float elev);

/* --- the horizon field ---------------------------------------------------
   Baked once on a regular lattice and *interpolated* for every mesh vertex,
   instead of marched at the vertex. Marching at the vertex made the shadow a
   function of the point set, and the point set is what the LOD changes: a tier
   swap re-baked the horizon at new vertices, a facet flipped from lit to
   shadowed, and 9.7% of a distant frame changed brightness -- measured, with
   the lod column of --flicker. One field, sampled bilinearly, is the same light
   at every tier. It also takes the 144-step march out of every chunk rebuild,
   which is most of what a rebuild costs. */
#define HOR_STEP 4                      /* cells between lattice points */
#define HOR_G (N / HOR_STEP)
static float hor_grid[HOR_G * HOR_G * SUN_SECTORS];

void bake_horizon_grid(void) {
    for (int j = 0; j < HOR_G; j++)
        for (int i = 0; i < HOR_G; i++) {
            float x = (float)(i * HOR_STEP) * CELL - TERRAIN_WORLD * 0.5f;
            float z = (float)(j * HOR_STEP) * CELL - TERRAIN_WORLD * 0.5f;
            horizon_at(x, z, sample_height(x, z), 1,
                       &hor_grid[(j * HOR_G + i) * SUN_SECTORS]);
        }
}

/* The field itself, for the renderer: two filterable images sampled per
   fragment, so the shadow has the screen's resolution instead of the mesh's. */
const float *horizon_field(void) { return hor_grid; }

/* Sampled on a 48x48 lattice rather than per grid cell: this is a number in the
   capture sidecar, and marching the horizon for every cell of a world-scale
   grid to produce it is exactly the cost this change removed. */
int shadowed_pct(void) {
    float az, el;
    sun_angles(day_hours, &az, &el);
    const int S = 48;
    int lit = 0;
    float h[SUN_SECTORS];
    for (int zi = 0; zi < S; zi++) {
        for (int xi = 0; xi < S; xi++) {
            float x = (xi / (float)(S - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            float z = (zi / (float)(S - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            float y = surface_height(x, z);
            if (y < -1e8f) { lit++; continue; }
            horizon_at(x, z, y, 1, h);
            if (shadow_lit(h, az, el) > 0.5f) lit++;
        }
    }
    return 100 * (S * S - lit) / (S * S);
}

/* Bilinear read of the baked surface colours at an arbitrary world point. */
void sample_rgb(const float *cr, const float *cg, const float *cb,
                       float x, float z, float *o) {
    float gx = (x + TERRAIN_WORLD * 0.5f) / CELL;
    float gz = (z + TERRAIN_WORLD * 0.5f) / CELL;
    int x0 = (int)floorf(gx), z0 = (int)floorf(gz);
    if (x0 < 0) x0 = 0; if (x0 > N - 2) x0 = N - 2;
    if (z0 < 0) z0 = 0; if (z0 > N - 2) z0 = N - 2;
    float fx = gx - x0, fz = gz - z0;
    if (fx < 0.0f) fx = 0.0f; if (fx > 1.0f) fx = 1.0f;
    if (fz < 0.0f) fz = 0.0f; if (fz > 1.0f) fz = 1.0f;
    int i00 = z0 * N + x0, i10 = i00 + 1, i01 = i00 + N, i11 = i01 + 1;
    #define SAMP(a) ((a[i00]*(1-fx)+a[i10]*fx)*(1-fz) + (a[i01]*(1-fx)+a[i11]*fx)*fz)
    o[0] = SAMP(cr); o[1] = SAMP(cg); o[2] = SAMP(cb);
    #undef SAMP
}

/* What colour of light does the ground around this point throw back? Four
   probes per azimuth sector, weighted toward the near ground. Deliberately not
   raycast: a bounce probe wants the AVERAGE of what is out there, and an
   occlusion test would only re-derive sky_ao. */
/* What colour of light does the ground around this point throw back? Four
   probes per azimuth sector, weighted toward the near ground. Deliberately not
   raycast: a bounce probe wants the AVERAGE of what is out there, and an
   occlusion test would only re-derive sky_ao. */
void bounce_at(float x, float z, float y, const float *cr,
                      const float *cg, const float *cb, float *out) {
    static const float D[4] = { 26.0f, 55.0f, 95.0f, 150.0f };
    for (int k = 0; k < SUN_SECTORS; k++) {
        float a = (float)k * 6.28318531f / (float)SUN_SECTORS;
        float dx = cosf(a), dz = sinf(a);
        float wr = 0.0f, wg = 0.0f, wb = 0.0f, ws = 0.0f;
        for (int q = 0; q < 4; q++) {
            float d = D[q];
            float px = x + dx * d, pz = z + dz * d;
            float h = sample_height(px, pz);
            if (h < -1e8f) continue;
            float c[3];
            sample_rgb(cr, cg, cb, px, pz, c);
            float w = 1.0f / (1.0f + d * 0.012f);
            /* a wall of ground above us faces away, so it lights us less than
               a field at our own level does */
            float dy = (h - y) / d;
            if (dy > 0.0f) w /= 1.0f + dy * 1.6f;
            wr += c[0] * w; wg += c[1] * w; wb += c[2] * w; ws += w;
        }
        float *o = out + k * 3;
        if (ws > 1e-4f) {
            o[0] = wr / ws; o[1] = wg / ws; o[2] = wb / ws;
        } else {
            o[0] = 0.30f; o[1] = 0.32f; o[2] = 0.20f;
        }
    }
}

/* Trees bucketed so a horizon query only looks at the crowns that can matter:
   110 world units is the reach of a crown in the shade, so the 3x3 bucket
   neighbourhood around a point holds every tree that can occlude it. */


int tree_bucket_of(float v) {
    int i = (int)floorf((v + TERRAIN_WORLD * 0.5f + TREE_BUCKET) / TREE_BUCKET);
    if (i < 0) i = 0;
    if (i >= tree_nb) i = tree_nb - 1;
    return i;
}

void build_tree_index(void) {
    free(tree_bstart); tree_bstart = NULL;
    free(tree_blist);  tree_blist = NULL;
    tree_nb = (int)(TERRAIN_WORLD / TREE_BUCKET) + 3;
    int nb = tree_nb * tree_nb;
    tree_bstart = (int *)calloc((size_t)nb + 1, sizeof(int));
    if (!tree_bstart) return;
    if (!tree_count) return;
    for (int i = 0; i < tree_count; i++)
        tree_bstart[tree_bucket_of(trees[i].z) * tree_nb + tree_bucket_of(trees[i].x)]++;
    int total = 0;
    for (int b = 0; b < nb; b++) { int c = tree_bstart[b]; tree_bstart[b] = total; total += c; }
    tree_bstart[nb] = total;
    tree_blist = (int *)malloc((size_t)(total ? total : 1) * sizeof(int));
    int *cur = (int *)malloc((size_t)nb * sizeof(int));
    if (!tree_blist || !cur) { free(cur); free(tree_blist); free(tree_bstart); tree_blist = NULL; tree_bstart = NULL; return; }
    memcpy(cur, tree_bstart, (size_t)nb * sizeof(int));
    for (int i = 0; i < tree_count; i++)
        tree_blist[cur[tree_bucket_of(trees[i].z) * tree_nb + tree_bucket_of(trees[i].x)]++] = i;
    free(cur);
}

/* Eight azimuth sectors of sky occlusion at a point on the surface: the
   highest thing in that direction, clamped. `with_trees` adds the crowns,
   which is what puts the ground in shade in a forest. */
void horizon_at(float x, float z, float y, int with_trees, float *out) {
    const float step = 1.7f * CELL;
    const int STEPS = 18;
    for (int k = 0; k < SUN_SECTORS; k++) {
        float a = (float)k * 6.28318531f / (float)SUN_SECTORS;
        float dx = cosf(a), dz = sinf(a);
        float best = 0.0f;
        for (int i = 1; i <= STEPS; i++) {
            float t = step * (float)i;
            float g = sample_height(x + dx * t, z + dz * t);
            if (g < -1e8f) break;
            float ang = atan2f(g - y, t);
            if (ang > best) best = ang;
            if (best > 1.45f) break;
        }
        out[k] = best;
    }
    if (!with_trees || !tree_blist) return;
    /* Only the crowns that stand *at* the point: the mesh cannot resolve a
       40-unit cast shadow (points are 15 units apart), so a long one becomes a
       hard-edged dark polygon lying on the slope. Short range keeps the shade
       where a canopy actually is, and keeps the dusk forest dark. */
    const float reach = TREE_BUCKET;
    int bx = tree_bucket_of(x), bz = tree_bucket_of(z);
    for (int nz = bz - 1; nz <= bz + 1; nz++) {
        if (nz < 0 || nz >= tree_nb) continue;
        for (int nx = bx - 1; nx <= bx + 1; nx++) {
            if (nx < 0 || nx >= tree_nb) continue;
            int b = nz * tree_nb + nx;
            for (int q = tree_bstart[b]; q < tree_bstart[b + 1]; q++) {
                const tree_t *t = &trees[tree_blist[q]];
                float dx = x - t->x, dz = z - t->z;
                float d2 = dx * dx + dz * dz;
                if (d2 > reach * reach || d2 < 1e-4f) continue;
                float d = sqrtf(d2);
                /* A crown is not a solid slab: it is porous, and its shadow is
                   dappled. Taking the full angular height made a single tree at
                   10:00 throw a 50-unit shadow across a meadow whose mesh points
                   are 15 units apart -- a handful of vertices went fully dark
                   and the ground showed a hard-edged dark polygon that reads as
                   floating geometry and changes shape whenever the LOD changes
                   the point set. 0.72 keeps dense stands (and any low sun, which
                   is where long shadows earn their keep) and takes the slab out
                   of the open. */
                float ang = atan2f(t->y + t->h * 0.92f - y, d) * 0.72f;
                if (ang < 0.03f) continue;
                float az = atan2f(dz, dx);
                if (az < 0.0f) az += 6.28318531f;
                int sec = (int)floorf(az * (float)SUN_SECTORS / 6.28318531f + 0.5f) & (SUN_SECTORS - 1);
                /* spread into the neighbours at a fraction: without it the
                   shadow jumps between sectors as the sun crosses one */
                if (ang > out[sec]) out[sec] = ang;
                float half = ang * 0.55f;
                int a1 = (sec + 1) & (SUN_SECTORS - 1), a0 = (sec + SUN_SECTORS - 1) & (SUN_SECTORS - 1);
                if (half > out[a1]) out[a1] = half;
                if (half > out[a0]) out[a0] = half;
            }
        }
    }
}

/* Interpolated the same way the shader does it, for a point whose horizon is
   already in hand, and for the sampled world figure the log reports. */
float shadow_lit(const float *h, float az, float elev) {
    float u = az * (float)SUN_SECTORS / 6.28318531f;
    if (u < 0.0f) u += (float)SUN_SECTORS;
    int k0 = (int)floorf(u) & (SUN_SECTORS - 1);
    int k1 = (k0 + 1) & (SUN_SECTORS - 1);
    float f = u - floorf(u);
    float occ = h[k0] * (1.0f - f) + h[k1] * f;
    float t = (elev - (occ - 0.03f)) / 0.06f;
    if (t < 0.0f) t = 0.0f;
    if (t > 1.0f) t = 1.0f;
    return t * t * (3.0f - 2.0f * t);
}

/* How much of the sky this point can see, 0..1. Eight short rays at ~30
   degrees above horizontal: valleys, the base of the massif and the foot of a
   hill come back dark, ridges and open meadow bright. Baked once for the same
   reason as the sun shadow -- ambient occlusion is free at frame time if it is
   not evaluated at frame time. */
float sky_occlusion(float x, float y, float z) {
    const int DIRS = 8, STEPS = 4;
    int hit = 0;
    for (int d = 0; d < DIRS; d++) {
        float a = (float)d * 6.28318531f / (float)DIRS;
        float dx = cosf(a), dz = sinf(a);
        for (int i = 1; i <= STEPS; i++) {
            float t = (float)i * 1.4f * CELL;
            float g = sample_height(x + dx * t, z + dz * t);
            if (g < -1e8f) break;
            if (g > y + t * 0.55f) { hit++; break; }
        }
    }
    return (float)hit / (float)DIRS;
}

/* deterministic per-facet hash, 0..1 */
float facet_hash(int tri) {
    unsigned h = (unsigned)tri * 2654435761u;
    h ^= h >> 15;
    return (float)(h & 1023u) / 1023.0f;
}

/* Low-poly look comes from facets being *distinct*, not from smooth shading.
   Four discrete shade steps instead of a continuous multiplier: a gradient of
   the same size reads as smooth, four steps read as polygons. */


/* Height of the drawn surface. The planar mesh below interpolates the same
   grid, so bilinear is the right answer for placement; the small sag inside a
   facet is what chunk_build() corrects afterwards. */
float surface_height(float x, float z) {
    return sample_height(x, z);
}

/* River: a polyline walked down the mountain by steepest descent, then carved
   into the heightfield as a parabolic channel. Water is a ribbon emitted at the
   path height, so it always sits on its own bed instead of floating. */

/* A river network is a list of SEGMENTS, not a polyline: tributaries join the
   trunk, so the drawing is a tree and "the previous point" is meaningless
   across a junction. Each segment carries its own water level and half width,
   which is what lets the channel narrow as it climbs. */

/* The channel has to be several cells wide or the grid can miss it: a trench
   narrower than CELL loses the carve between vertices and the water ribbon
   ends up lying on the un-carved surface. */
/* one colour for every water surface: the sea plane and the river painted
   into the terrain have to match or the mouth shows a seam */


/* half width by drainage area: a stream at the top of a range is a few units
   wide, the trunk at the coast is 24. One constant width reads as a canal. */



/* Distance from (x,z) to the river centreline; *w gets the water level there.
   Returns 1e9 when there is no river. */
/* Bucket index over the segments. The carve and every per-facet water query
   used to walk all ~400 segments, so both were O(cells x segments) -- the
   second-largest cost in a big world after the horizon march, and the reason
   the river can never become a per-point function while it stays linear. Each
   segment registers in every bucket its box (grown by the carve's outer
   radius) touches, so a point close enough to care about always finds it. */


int seg_bucket_of(float v) {
    int i = (int)floorf((v + TERRAIN_WORLD * 0.5f + SEG_BUCKET) / SEG_BUCKET);
    if (i < 0) i = 0;
    if (i >= seg_nb) i = seg_nb - 1;
    return i;
}

void build_seg_index(void) {
    free(seg_bstart); seg_bstart = NULL;
    free(seg_blist);  seg_blist = NULL;
    seg_nb = (int)(TERRAIN_WORLD / SEG_BUCKET) + 3;
    int nb = seg_nb * seg_nb;
    seg_bstart = (int *)calloc((size_t)nb + 1, sizeof(int));
    if (!seg_bstart) return;
    if (!seg_n) return;
    for (int i = 0; i < seg_n; i++) {
        float pad = seg_hw[i] + RIVER_BANK + 2.0f;
        int x0 = seg_bucket_of(fminf(seg_x0[i], seg_x1[i]) - pad);
        int x1 = seg_bucket_of(fmaxf(seg_x0[i], seg_x1[i]) + pad);
        int z0 = seg_bucket_of(fminf(seg_z0[i], seg_z1[i]) - pad);
        int z1 = seg_bucket_of(fmaxf(seg_z0[i], seg_z1[i]) + pad);
        for (int bz = z0; bz <= z1; bz++)
            for (int bx = x0; bx <= x1; bx++) seg_bstart[bz * seg_nb + bx]++;
    }
    int total = 0;
    for (int b = 0; b < nb; b++) { int c = seg_bstart[b]; seg_bstart[b] = total; total += c; }
    seg_bstart[nb] = total;
    seg_blist = (int *)malloc((size_t)(total ? total : 1) * sizeof(int));
    int *cur = (int *)malloc((size_t)nb * sizeof(int));
    if (!seg_blist || !cur) { free(cur); free(seg_blist); free(seg_bstart); seg_blist = NULL; seg_bstart = NULL; return; }
    memcpy(cur, seg_bstart, (size_t)nb * sizeof(int));
    for (int i = 0; i < seg_n; i++) {
        float pad = seg_hw[i] + RIVER_BANK + 2.0f;
        int x0 = seg_bucket_of(fminf(seg_x0[i], seg_x1[i]) - pad);
        int x1 = seg_bucket_of(fmaxf(seg_x0[i], seg_x1[i]) + pad);
        int z0 = seg_bucket_of(fminf(seg_z0[i], seg_z1[i]) - pad);
        int z1 = seg_bucket_of(fmaxf(seg_z0[i], seg_z1[i]) + pad);
        for (int bz = z0; bz <= z1; bz++)
            for (int bx = x0; bx <= x1; bx++) seg_blist[cur[bz * seg_nb + bx]++] = i;
    }
    free(cur);
}

/* Nearest point on the network. hw comes back as the half width there, so
   callers compare distance against the river's own width instead of a
   constant. Falls back to the full scan while the network is still being
   traced (the index can only be built once the segments are final). */
float river_query(float x, float z, float *w, float *fx, float *fz,
                         float *hw) {
    float best = 1e18f;
    const int *list = NULL;
    int n = seg_n;
    if (seg_blist) {
        int b = seg_bucket_of(z) * seg_nb + seg_bucket_of(x);
        list = seg_blist + seg_bstart[b];
        n = seg_bstart[b + 1] - seg_bstart[b];
    }
    for (int k = 0; k < n; k++) {
        int i = list ? list[k] : k;
        float ax = seg_x0[i], az = seg_z0[i];
        float vx = seg_x1[i] - ax, vz = seg_z1[i] - az;
        float L2 = vx*vx + vz*vz;
        float t = L2 > 1e-9f ? ((x-ax)*vx + (z-az)*vz) / L2 : 0.0f;
        if (t < 0.0f) t = 0.0f;
        if (t > 1.0f) t = 1.0f;
        float dx = x - (ax + vx*t), dz = z - (az + vz*t);
        float d2 = dx*dx + dz*dz;
        if (d2 < best) {
            best = d2;
            if (w)  *w  = seg_w[i];
            if (hw) *hw = seg_hw[i];
            if (fx) { float il = L2 > 1e-9f ? 1.0f/sqrtf(L2) : 0.0f; *fx = vx*il; *fz = vz*il; }
        }
    }
    return seg_n ? sqrtf(best) : 1e9f;
}

/* Steepest descent with momentum: pure gradient descent stalls in every flat
   basin on the way down, momentum carries it through. The river is only kept
   if it actually reaches the sea, so a failed attempt is simply retried with a
   different heading. */
/* --- hydrology -------------------------------------------------------------
   Rivers run where water actually goes. Two passes over the eroded grid:

   1. Priority-flood. Every pit is filled to its spill height. A noise field is
      full of pits, and a pit with no outlet is not a lake, it is a hole in the
      watershed -- filling gives each one an outlet, and the fill depth is
      exactly the lake surface. Lakes shallower than a cell or smaller than a
      pond are dropped back to the ground, or the island is peppered with
      puddles.
   2. Flow accumulation (D8). Each cell drains into its steepest neighbour;
      summing the upstream count gives the trunk of each watershed, and the
      biggest trunk is the river.

   Both are O(n log n) on the 74x74 grid, once, at load. ponytail: one trunk,
   extracted from the largest accumulation; tributaries are the natural next
   step and need a threshold on the accumulation, not new machinery. */


void heap_push(float k, int i) {
    if (heap_n >= HEAP_MAX) return;
    int c = heap_n++;
    while (c > 0) {
        int p = (c - 1) / 2;
        if (heap_k[p] <= k) break;
        heap_k[c] = heap_k[p]; heap_i[c] = heap_i[p];
        c = p;
    }
    heap_k[c] = k; heap_i[c] = i;
}

int heap_pop(float *k) {
    int top = heap_i[0];
    *k = heap_k[0];
    if (--heap_n > 0) {
        float kk = heap_k[heap_n];
        int ii = heap_i[heap_n], c = 0;
        for (;;) {
            int l = 2 * c + 1, r = l + 1, m = c;
            float mk = kk;
            if (l < heap_n && heap_k[l] < mk) { m = l; mk = heap_k[l]; }
            if (r < heap_n && heap_k[r] < mk) { m = r; }
            if (m == c) break;
            heap_k[c] = heap_k[m]; heap_i[c] = heap_i[m];
            c = m;
        }
        heap_k[c] = kk; heap_i[c] = ii;
    }
    return top;
}

int h_cmp(const void *a, const void *b) {
    float ha = h_fill[*(const int *)a], hb = h_fill[*(const int *)b];
    return ha < hb ? 1 : (ha > hb ? -1 : 0);      /* descending */
}



void build_hydrology(unsigned seed) {
    for (int i = 0; i < N * N; i++) {
        h_src[i] = h_fill[i] = heights[i];
        lake_cell[i] = 0;
    }
    /* --- 1: priority-flood from every cell that already drains --- */
    heap_n = 0;
    for (int i = 0; i < N * N; i++) {
        h_fill[i] = 3.0e38f;
    }
    for (int zi = 0; zi < N; zi++) {
        for (int xi = 0; xi < N; xi++) {
            int i = zi * N + xi;
            if (heights[i] > 0.0f && xi && zi && xi < N - 1 && zi < N - 1) continue;
            h_fill[i] = heights[i];
            heap_push(heights[i], i);
        }
    }
    while (heap_n > 0) {
        float h0;
        int c = heap_pop(&h0);
        int cx = c % N, cz = c / N;
        for (int dz = -1; dz <= 1; dz++) {
            for (int dx = -1; dx <= 1; dx++) {
                if (!dx && !dz) continue;
                int nx = cx + dx, nz = cz + dz;
                if (nx < 0 || nz < 0 || nx >= N || nz >= N) continue;
                int n = nz * N + nx;
                if (h_fill[n] < 3.0e37f) continue;
                float f = heights[n] > h0 ? heights[n] : h0;
                h_fill[n] = f;
                if (f > heights[n] + LAKE_DEPTH) lake_cell[n] = 1;
                heap_push(f, n);
            }
        }
    }
    /* drop the ponds: connected components below the minimum area go back to
       being ground, or the meadow is covered in puddles */
    {
        static int stack[N * N];
        static unsigned char seen[N * N];
        for (int i = 0; i < N * N; i++) seen[i] = 0;
        for (int i = 0; i < N * N; i++) {
            if (!lake_cell[i] || seen[i]) continue;
            int sp = 0, cnt = 0;
            stack[sp++] = i; seen[i] = 1;
            while (sp > 0) {
                int c = stack[--sp];
                cnt++;
                int cx = c % N, cz = c / N;
                for (int dz = -1; dz <= 1; dz++)
                    for (int dx = -1; dx <= 1; dx++) {
                        int nx = cx + dx, nz = cz + dz;
                        if (nx < 0 || nz < 0 || nx >= N || nz >= N) continue;
                        int n = nz * N + nx;
                        if (!lake_cell[n] || seen[n]) continue;
                        seen[n] = 1;
                        stack[sp++] = n;
                    }
            }
            if (cnt < MIN_LAKE_CELLS) {
                /* second pass over the component to clear it */
                int sp2 = 0;
                stack[sp2++] = i;
                lake_cell[i] = 2;          /* 2 = visited-and-rejected */
                while (sp2 > 0) {
                    int c = stack[--sp2];
                    lake_cell[c] = 0;
                    h_fill[c] = h_src[c];
                    int cx = c % N, cz = c / N;
                    for (int dz = -1; dz <= 1; dz++)
                        for (int dx = -1; dx <= 1; dx++) {
                            int nx = cx + dx, nz = cz + dz;
                            if (nx < 0 || nz < 0 || nx >= N || nz >= N) continue;
                            int n = nz * N + nx;
                            if (lake_cell[n] != 1) continue;
                            lake_cell[n] = 2;
                            stack[sp2++] = n;
                        }
                }
            } else {
                for (int k = 0; k < N * N; k++) if (lake_cell[k] == 2) lake_cell[k] = 1;
            }
        }
        for (int i = 0; i < N * N; i++) if (lake_cell[i] == 2) lake_cell[i] = 1;
    }
    /* The bed is left where the flood found it: the surface is its own geometry
       now (settle_lakes + chunk_build), so a lake keeps a real basin. */

    /* --- 2: a strictly descending surface to steer the flow ---
       Filled ground is FLAT, and D8 needs a strict descent: on a flat basin
       every cell has "no lower neighbour", so the river stops exactly where the
       lake starts. Walk outward from the cells that already drain (the sea and
       anything with a lower neighbour) and lift each flat cell a hair above the
       one it came from. The result is monotone everywhere, and the lift is
       1e-3 -- invisible in the terrain, decisive for the flow. */
    static float h_drain[N * N];
    static int queue[N * N];
    for (int i = 0; i < N * N; i++) h_drain[i] = h_fill[i];
    {
        int qh = 0, qt = 0;
        static unsigned char queued[N * N];
        for (int i = 0; i < N * N; i++) queued[i] = 0;
        for (int i = 0; i < N * N; i++) {
            int cx = i % N, cz = i / N;
            int lower = h_fill[i] <= 0.0f;
            for (int dz = -1; dz <= 1 && !lower; dz++)
                for (int dx = -1; dx <= 1 && !lower; dx++) {
                    if (!dx && !dz) continue;
                    int nx = cx + dx, nz = cz + dz;
                    if (nx < 0 || nz < 0 || nx >= N || nz >= N) continue;
                    if (h_fill[nz * N + nx] < h_fill[i]) lower = 1;
                }
            if (lower) { queue[qt++] = i; queued[i] = 1; }
        }
        while (qh < qt) {
            int c = queue[qh++];
            int cx = c % N, cz = c / N;
            for (int dz = -1; dz <= 1; dz++)
                for (int dx = -1; dx <= 1; dx++) {
                    if (!dx && !dz) continue;
                    int nx = cx + dx, nz = cz + dz;
                    if (nx < 0 || nz < 0 || nx >= N || nz >= N) continue;
                    int n = nz * N + nx;
                    if (queued[n]) continue;
                    if (h_fill[n] != h_fill[c]) continue;     /* only flats */
                    h_drain[n] = h_drain[c] + 1.0e-3f;
                    queued[n] = 1;
                    queue[qt++] = n;
                }
        }
    }

    /* --- 3: flow accumulation --- */
    for (int i = 0; i < N * N; i++) {
        h_order[i] = i;
        h_acc[i] = 1.0f;
        h_down[i] = -1;
        if (h_fill[i] <= 0.0f) continue;           /* the sea does not drain */
        int cx = i % N, cz = i / N;
        int best = -1;
        /* Flow runs on the FILLED surface, not the drawn one: a pit shallower
           than a lake still has to drain, and on the raw heights it is a
           dead end that stops the river in the middle of the meadow. */
        /* Steepest descent by SLOPE, not by height: a diagonal step is 1.41x
           longer, and on the sub-millimetre gradient a filled basin has, a
           fixed height penalty of any size closes the outlet entirely and the
           river stops in the meadow. */
        float best_slope = 0.0f;
        for (int dz = -1; dz <= 1; dz++) {
            for (int dx = -1; dx <= 1; dx++) {
                if (!dx && !dz) continue;
                int nx = cx + dx, nz = cz + dz;
                if (nx < 0 || nz < 0 || nx >= N || nz >= N) continue;
                int n = nz * N + nx;
                float dist = (dx && dz) ? 1.41421356f : 1.0f;
                float sl = (h_drain[i] - h_drain[n]) / dist;
                if (sl > best_slope) { best_slope = sl; best = n; }
            }
        }
        h_down[i] = best;
    }
    qsort(h_order, N * N, sizeof(int), h_cmp);
    for (int k = 0; k < N * N; k++) {
        int i = h_order[k];
        if (h_down[i] >= 0) h_acc[h_down[i]] += h_acc[i];
    }

    /* --- 4: the network ---
       Trunk first, then the biggest tributaries that are not already on it.
       Every river is traced downstream from its spring, so a tributary ends
       exactly where it joins the trunk instead of crossing it. */
    seg_n = 0;
    river_count = 0;
    river_lo = 1e9f;
    river_hi = -1e9f;
    /* The bucket index still describes the *previous* network (build_seg_index
       runs after this), and the tributary skip below asks river_query where the
       rivers are. Drop it, so river_query scans the segments built so far --
       which is what a fresh process does, and therefore what a rebuild must do
       too. Without this, a world rebuilt in place came out with a different
       river network from the same seed. */
    free(seg_bstart); seg_bstart = NULL;
    free(seg_blist);  seg_blist = NULL;
    seg_nb = 0;
    int mouth = -1;
    float best_acc = 0.0f;
    for (int i = 0; i < N * N; i++) {
        if (h_fill[i] <= 0.5f) continue;
        if (h_acc[i] > best_acc) { best_acc = h_acc[i]; mouth = i; }
    }
    if (mouth < 0 || best_acc < 12.0f) return;   /* no watershed worth drawing */

    static int path[RIVER_MAX];
    int want = terrain_gen(seed).rivers;
    for (int r = 0; r < want && seg_n < RIVER_MAX_SEG - 4; r++) {
        int start = mouth;
        if (r > 0) {
            /* the next biggest drainage that is not already in the network */
            int best = -1;
            float ba = 0.0f;
            for (int i = 0; i < N * N; i++) {
                if (h_fill[i] <= 0.5f || h_acc[i] < 10.0f || h_acc[i] <= ba) continue;
                float x = (i % N) / (float)(N - 1) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
                float z = (i / N) / (float)(N - 1) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
                if (river_query(x, z, NULL, NULL, NULL, NULL) < 26.0f) continue;
                best = i; ba = h_acc[i];
            }
            if (best < 0) break;
            start = best;
        }
        /* upstream to the spring */
        static int up[RIVER_MAX];
        int nu = 0;
        int c = start;
        while (nu < RIVER_MAX) {
            up[nu++] = c;
            int cx = c % N, cz = c / N, prev = -1;
            float pa = 0.0f;
            for (int dz = -1; dz <= 1; dz++)
                for (int dx = -1; dx <= 1; dx++) {
                    int nx = cx + dx, nz = cz + dz;
                    if (nx < 0 || nz < 0 || nx >= N || nz >= N) continue;
                    int n = nz * N + nx;
                    if (h_down[n] != c) continue;
                    if (h_acc[n] > pa) { pa = h_acc[n]; prev = n; }
                }
            /* A river starts where its catchment is big enough to feed one,
               not at the summit: tracing to the top draws a sheet of water
               straight down the mountain face and reads as a waterfall. */
            if (prev < 0 || h_acc[prev] < 6.0f) break;
            c = prev;
        }
        int np = 0;
        for (int k = nu - 1; k >= 0 && np < RIVER_MAX; k--) path[np++] = up[k];
        /* then down: to the sea for the trunk, to the network for a tributary */
        int c2 = start;
        while (np < RIVER_MAX) {
            int dn = h_down[c2];
            if (dn < 0) break;
            if (r > 0) {
                float x = (dn % N) / (float)(N - 1) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
                float z = (dn / N) / (float)(N - 1) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
                if (river_query(x, z, NULL, NULL, NULL, NULL) < 10.0f) { path[np++] = dn; break; }
            }
            c2 = dn;
            path[np++] = c2;
            if (h_fill[c2] <= 0.0f) break;
        }
        /* Meanders: a river on flat ground wanders, and a straight line from
           spring to sea is the single clearest sign that water was not what
           drew it. Each interior point is pushed sideways by a slow sine whose
           amplitude grows with the river's size and dies on steep reaches --
           mountain water runs straight down the fall line, lowland water
           loops. Endpoints are pinned so tributaries still meet the trunk and
           the mouth still reaches the sea. */
        float px[RIVER_MAX], pz[RIVER_MAX];
        for (int k = 0; k < np; k++) {
            px[k] = (path[k] % N) / (float)(N - 1) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            pz[k] = (path[k] / N) / (float)(N - 1) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
        }
        {
            float s = 0.0f;
            for (int k = 1; k + 1 < np; k++) {
                float dx = px[k + 1] - px[k - 1], dz = pz[k + 1] - pz[k - 1];
                float l = sqrtf(dx * dx + dz * dz);
                if (l < 1e-3f) continue;
                float nx = -dz / l, nz = dx / l;
                s += CELL;
                float t = sqrtf(h_acc[path[k]] / best_acc);
                /* how steep is the reach? straight where it is steep */
                float drop = h_fill[path[k]] - h_fill[path[k + 1]];
                float flat = 1.0f - fminf(drop / (1.6f * CELL), 1.0f);
                float amp = CELL * (0.35f + 0.75f * t) * flat;
                float offs = amp * sinf(s * (6.2831853f / (14.0f * CELL))
                                        + (float)(seed & 255u) * 0.19f);
                px[k] += nx * offs;
                pz[k] += nz * offs;
            }
            /* the mouth keeps its position: a meander must not move where the
               river meets the sea, or the outlet wanders off the coast */
            px[np - 1] = (path[np - 1] % N) / (float)(N - 1) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            pz[np - 1] = (path[np - 1] / N) / (float)(N - 1) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
        }
        for (int k = 0; k + 1 < np && seg_n < RIVER_MAX_SEG; k++) {
            int a = path[k];
            seg_x0[seg_n] = px[k];
            seg_z0[seg_n] = pz[k];
            seg_x1[seg_n] = px[k + 1];
            seg_z1[seg_n] = pz[k + 1];
            seg_w[seg_n] = h_fill[a];
            /* width follows drainage area, so the channel narrows as it climbs
               instead of running as a canal from the summit to the sea */
            float t = sqrtf(h_acc[a] / best_acc);
            seg_hw[seg_n] = RIVER_HW_MIN + (RIVER_HW_MAX - RIVER_HW_MIN) * t;
            if (h_fill[a] > river_hi) river_hi = h_fill[a];
            if (h_fill[a] < river_lo) river_lo = h_fill[a];
            seg_n++;
        }
        river_count++;
    }
}

/* The still-water level at this point, or 0. Distinct from the bed height now:
   the bed is a basin, the level is where the water sits. Exactly the lake mask,
   not a dilation of it: the plane must sit strictly over lowered bed, or a
   chord between a lowered mesh point and a natural one rises through it and
   draws a sliver of sand lying on the water. */
float lake_level_near(float x, float z, int r) {
    int xi0 = (int)((x + TERRAIN_WORLD * 0.5f) / CELL);
    int zi0 = (int)((z + TERRAIN_WORLD * 0.5f) / CELL);
    float lv = 0.0f;
    for (int dz = -r; dz <= r; dz++)
        for (int dx = -r; dx <= r; dx++) {
            int xi = xi0 + dx, zi = zi0 + dz;
            if (xi < 0 || zi < 0 || xi >= N || zi >= N) continue;
            if (!lake_cell[zi * N + xi]) continue;
            float f = h_fill[zi * N + xi];
            if (lv <= 0.0f || f < lv) lv = f;
        }
    return lv;
}

float lake_level_at(float x, float z) { return lake_level_near(x, z, 0); }

int lake_at(float x, float z) {
    int xi = (int)((x + TERRAIN_WORLD * 0.5f) / CELL);
    int zi = (int)((z + TERRAIN_WORLD * 0.5f) / CELL);
    if (xi < 0 || zi < 0 || xi >= N || zi >= N) return 0;
    return lake_cell[zi * N + xi];
}

/* Cut the channel. Inside the local half width the bed lies below the water
   level (the surface is its own geometry); outside it the ground blends back
   up to untouched height over RIVER_BANK. Width comes from the segment, so the
   channel narrows as it climbs. */
/* Valleys, cut by the rivers that are already there.

   This is a *landform* pass, not a hydraulic solver. Two attempts at real flow
   erosion failed for a reason worth recording: D8 routing on this noise field
   fragments into thousands of small basins (accumulation tops out at ~9k cells
   of 1.4M), so almost no water gathers and almost nothing erodes. A proper
   fix is a priority-flood hydraulic solver over many iterations -- hours per
   world, for a shape we can also get by decree.

   The rivers are traced, ordered and trusted; the terrain around them is what
   is wrong. So each river stamps a valley: a V profile whose depth and width
   grow with the river's own width, which is exactly the "valleys widen
   downstream" property without simulating a drop of water. Only lowering is
   done -- a valley pass that raises ground is how you get lakes in meadows.

   Why it is worth its cost: a range whose flanks all drain into one channel
   reads as rock, where a range with the same silhouette does not. The player
   also gets the thing terrain is *for* -- a route along the water, a ridge to
   cross, a valley to be trapped in. */
/* Valleys, cut by the rivers that are already there.

   Two attempts at real flow erosion failed for a reason worth recording: D8
   routing on this noise field fragments into thousands of small basins
   (accumulation tops out at ~9k cells of 1.4M), so almost no water gathers and
   almost nothing erodes. The honest fix is a priority-flood hydraulic solver
   over many iterations -- hours per world, for a shape we can also decree.

   The rivers are traced and trusted; it is the ground around them that is
   wrong. So the valley is defined *relative to the river*: the floor is the
   water level, the walls rise `depth` over `radius`, and only lowering is
   applied. That is the shape water actually leaves -- a channel at the bottom
   of a trough -- and it can never dig below its own river, which is what the
   first attempt did (carving 200 units down on a plain put the whole valley
   under the sea and the map filled with black holes).

   Depth and radius come from the river's own width, so tributaries cut grooves
   and trunks cut valleys -- the widening-downstream property, without a drop
   of simulated water. Relief caps it: on a plain a river cannot cut 300 units
   into ground that is only 20 units above the sea. */
/* Two-pass 3x3 chamfer distance transform, carrying the nearest source's
   payload (`clevel`) along. Used for river distance and for sea distance: it is
   within a few percent of Euclidean, which is all either of them needs. */
static void chamfer_2d(float *cdist, float *clevel, int cn) {
    for (int pass = 0; pass < 2; pass++) {
        int zstart = pass ? cn - 1 : 0, zend = pass ? -1 : cn, zstep = pass ? -1 : 1;
        for (int cz = zstart; cz != zend; cz += zstep) {
            int xstart = pass ? cn - 1 : 0, xend = pass ? -1 : cn, xstep = pass ? -1 : 1;
            for (int cx = xstart; cx != xend; cx += xstep) {
                int c = cz * cn + cx;
                for (int dz = -1; dz <= 1; dz++)
                    for (int dx = -1; dx <= 1; dx++) {
                        if (!dx && !dz) continue;
                        int nx = cx + dx, nz = cz + dz;
                        if (nx < 0 || nz < 0 || nx >= cn || nz >= cn) continue;
                        int n = nz * cn + nx;
                        float step = (dx && dz) ? 1.4142f : 1.0f;
                        if (cdist[n] + step < cdist[c]) {
                            cdist[c] = cdist[n] + step;
                            if (clevel) clevel[c] = clevel[n];
                        }
                    }
            }
        }
    }
}

/* The river distance field, coarse (VC cells per coarse cell) and kept because
   the geography and the sim ask where the water is, not just the carver. */
enum { RIV_VC = 16 };
static float riv_dist[(N / 16 + 2) * (N / 16 + 2)];
static float riv_level[(N / 16 + 2) * (N / 16 + 2)];

void carve_valleys(void) {
    if (!seg_n) return;

    /* Coarse fields, because a per-cell query cannot see far enough: river_query
       only searches the bucket the point is in, which is right for painting a
       25-unit bank and wrong for a 1000-unit valley. So rasterise the rivers on
       a coarse grid and run a two-pass chamfer distance transform (with the
       nearest river's water level carried along in the same pass). ~74 units
       per cell, bilinear when sampled, which keeps the profile smooth. */
    enum { VC = RIV_VC };
    int cn = N / VC + 1;
    float *cdist = riv_dist, *clevel = riv_level;
    static float cmax[(N / 16 + 2) * (N / 16 + 2)];
    for (int i = 0; i < cn * cn; i++) { cdist[i] = 1e6f; clevel[i] = 0.0f; cmax[i] = -1e30f; }

    for (int zi = 0; zi < N; zi++)
        for (int xi = 0; xi < N; xi++) {
            int c = (zi / VC) * cn + xi / VC;
            float h = heights[zi * N + xi];
            if (h > cmax[c]) cmax[c] = h;
        }

    for (int s = 0; s < seg_n; s++) {
        int ax = (int)((seg_x0[s] + TERRAIN_WORLD * 0.5f) / CELL) / VC;
        int az = (int)((seg_z0[s] + TERRAIN_WORLD * 0.5f) / CELL) / VC;
        int bx = (int)((seg_x1[s] + TERRAIN_WORLD * 0.5f) / CELL) / VC;
        int bz = (int)((seg_z1[s] + TERRAIN_WORLD * 0.5f) / CELL) / VC;
        if (ax < 0) ax = 0; if (ax >= cn) ax = cn - 1;
        if (az < 0) az = 0; if (az >= cn) az = cn - 1;
        if (bx < 0) bx = 0; if (bx >= cn) bx = cn - 1;
        if (bz < 0) bz = 0; if (bz >= cn) bz = cn - 1;
        int steps = abs(bx - ax) > abs(bz - az) ? abs(bx - ax) : abs(bz - az);
        if (steps < 1) steps = 1;
        for (int k = 0; k <= steps; k++) {
            int cx = ax + (bx - ax) * k / steps;
            int cz = az + (bz - az) * k / steps;
            int c = cz * cn + cx;
            cdist[c] = 0.0f;
            clevel[c] = seg_w[s];
        }
    }

    chamfer_2d(cdist, clevel, cn);

    for (int zi = 0; zi < N; zi++) {
        for (int xi = 0; xi < N; xi++) {
            int i = zi * N + xi;
            if (lake_cell[i]) continue;
            /* bilinear sample of the coarse fields */
            float fx = xi / (float)VC, fz = zi / (float)VC;
            int x0 = (int)fx, z0 = (int)fz;
            if (x0 >= cn - 1) x0 = cn - 2;
            if (z0 >= cn - 1) z0 = cn - 2;
            if (x0 < 0) x0 = 0;
            if (z0 < 0) z0 = 0;
            float tx = fx - x0, tz = fz - z0;
            int c00 = z0 * cn + x0, c10 = c00 + 1, c01 = c00 + cn, c11 = c01 + 1;
            float d = (cdist[c00] * (1 - tx) + cdist[c10] * tx) * (1 - tz)
                    + (cdist[c01] * (1 - tx) + cdist[c11] * tx) * tz;
            float wl = (clevel[c00] * (1 - tx) + clevel[c10] * tx) * (1 - tz)
                     + (clevel[c01] * (1 - tx) + clevel[c11] * tx) * tz;
            /* near the coast the river is at sea level, and a carved floor
               there is a sand flat, not a valley: leave coastal lowlands be */
            if (wl < 25.0f) continue;
            float local = (cmax[c00] * (1 - tx) + cmax[c10] * tx) * (1 - tz)
                        + (cmax[c01] * (1 - tx) + cmax[c11] * tx) * tz;
            /* meters: coarse distance in coarse cells -> world units */
            float dist = d * VC * CELL;
            float room = local - wl;                 /* rock above the river */
            if (room < 0.0f) room = 0.0f;
            float depth = 0.28f * room;
            if (depth > 180.0f) depth = 180.0f;
            if (depth < 20.0f) depth = 20.0f;        /* every river has a trough */
            float radius = 240.0f + 1.6f * depth;    /* deeper valleys are wider */
            if (dist > radius) continue;
            float k = 1.0f - dist / radius;
            k *= k;                                  /* flat floor, steep walls */
            /* Remove material rather than clamp to a profile height: clamping
               put a ceiling over everything within the radius, so peaks a few
               hundred metres from a creek were planed off and the alpine
               archetype stopped being alpine. */
            float target = heights[i] - depth * k;
            /* floor well above the water, or the valley bottom lands in the
               sand band (h < 3) and every eroded trough reads as a beach */
            if (target < wl + 12.0f) target = wl + 12.0f;
            if (target < heights[i]) heights[i] = target;
        }
    }
}

/* Lake beds, last of all the height passes, because carve_river lifts the cells
   around a lake to the river's own level and that raised bank is what poked up
   through the water. Lower only, over the same two-cell footprint the water
   plane covers: raising anything here would put a step in the bank, and a step
   is a straight line across the lake. Lowering can only push the bed away from
   the plane, so no chord between two mesh points 15 units apart can rise
   through the water -- and a bed that merely *follows* the level can, which is
   what the first version of this drew. */
/* A lake mask with a one-cell crack in it is a hole in the water: the river's
   course through the lake drains, so the flood leaves those cells dry, they keep
   the river's level instead of the lake's, and the bed -- lowered under the lake
   -- shows through the surface as a strip of sand lying across it. Close the
   mask: a cell most of whose neighbours are lake is lake, at their level. */
void close_lakes(void) {
    for (int zi = 0; zi < N; zi++) {
        for (int xi = 0; xi < N; xi++) {
            int i = zi * N + xi;
            if (lake_cell[i]) continue;
            int n = 0;
            float lv = 0.0f;
            for (int dz = -1; dz <= 1; dz++)
                for (int dx = -1; dx <= 1; dx++) {
                    int ax = xi + dx, az = zi + dz;
                    if ((!dx && !dz) || ax < 0 || az < 0 || ax >= N || az >= N) continue;
                    if (!lake_cell[az * N + ax]) continue;
                    n++;
                    float f = h_fill[az * N + ax];
                    if (lv <= 0.0f || f < lv) lv = f;   /* lowest, as in settle */
                }
            if (n >= 5) { lake_cell[i] = 1; h_fill[i] = lv; }
        }
    }
}

void settle_lakes(void) {
    for (int zi = 0; zi < N; zi++) {
        for (int xi = 0; xi < N; xi++) {
            int i = zi * N + xi;
            /* The *lowest* level touching this cell, its own included: where two
               lakes at different fills meet, a bed lowered under the higher one
               still stands above the lower one's surface and shows through it as
               a strip of sand. */
            /* Only the cells the flood actually called water. The one-cell ring
               used to be lowered as well, to keep a mesh chord from bridging a
               lowered cell to a dry one and standing through the plane -- but a
               lowered *ring* is a sunk bank: the shoreline floods by however
               far it was dropped, which at 2.5 units swallowed a strip of
               meadow. Facets sink their own bed vertices under the plane now,
               so the ring can keep its ground. */
            if (!lake_cell[i]) continue;
            float lv = h_fill[i];
            for (int dz = -1; dz <= 1; dz++)
                for (int dx = -1; dx <= 1; dx++) {
                    int ax = xi + dx, az = zi + dz;
                    if (ax < 0 || az < 0 || ax >= N || az >= N) continue;
                    if (!lake_cell[az * N + ax]) continue;
                    float f = h_fill[az * N + ax];
                    if (lv <= 0.0f || f < lv) lv = f;
                }
            if (lv <= 0.0f) continue;
            /* Just under the plane, not 2.5 under it. The deep version was
               load-bearing only while the bed *was* the waterline: it kept a
               chord from poking through. Facets now sink their own bed vertices
               under the plane (see chunk_build), so all this has to do is keep
               the bed below the surface, and 2.5 units of it is a 2.5-unit
               cliff at every shore -- seen from above, a dark band lying along
               the waterline. */
            if (heights[i] > lv - 0.6f) heights[i] = lv - 0.6f;
        }
    }
}

void carve_river(void) {
    if (!seg_n) return;
    for (int zi = 0; zi < N; zi++) {
        for (int xi = 0; xi < N; xi++) {
            float x = (xi / (float)(N - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            float z = (zi / (float)(N - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            int i = zi * N + xi;
            /* Inside a lake the surface is already flat at the water level and
               the river runs *through* it, not over it: carving there dug a
               trench across the lake bed and the ripple-shaded river facets
               showed up as a striped ribbon lying on the still water. */
            if (lake_cell[i]) continue;
            /* No rivers down cliff faces. The DEM traces steepest descent, and
               with alpine relief that includes near-vertical drops: painting
               the bed at water level there drew a white cascade up a rock wall.
               A river starts where the ground can hold one -- which is also
               where a real spring is. */
            if (!river_bed_ok(x, z)) continue;
            float w = 0.0f, hw = RIVER_HW_MIN;
            float d = river_query(x, z, &w, NULL, NULL, &hw);
            if (d > hw + RIVER_BANK) continue;
            float h = heights[i];
            if (d <= hw) {
                /* Below the water, not at it: the surface is its own geometry
                   now, and a bed at the water level would be coplanar with it
                   and z-fight. A few units, wider channels deeper. */
                float bed = w - (2.2f + 0.12f * hw);
                heights[i] = bed < h ? bed : h;
            } else {
                float u = (d - hw) / RIVER_BANK;
                if (u > 1.0f) u = 1.0f;
                float target = w + (h - w) * u;
                if (target < h) heights[i] = target;   /* carve only, never raise */
            }
        }
    }
}

/* One flat-shaded triangle for the props. Winding normal is flipped to face
   away from `inner`. The shade is baked into the colour here and the shader
   gets a normal blended toward the sun, so canopies darken on their far side
   without dropping below the ambient floor. */
void emit_tri(const float *p0, const float *p1, const float *p2,
                     const float *inner, const float *base, float jitter) {
    float u[3] = { p1[0]-p0[0], p1[1]-p0[1], p1[2]-p0[2] };
    float w[3] = { p2[0]-p0[0], p2[1]-p0[1], p2[2]-p0[2] };
    float n[3] = { u[1]*w[2]-u[2]*w[1], u[2]*w[0]-u[0]*w[2], u[0]*w[1]-u[1]*w[0] };
    float l = sqrtf(n[0]*n[0] + n[1]*n[1] + n[2]*n[2]);
    if (l < 1e-9f) return;
    n[0] /= l; n[1] /= l; n[2] /= l;
    if (inner) {
        float cx = (p0[0]+p1[0]+p2[0]) * (1.0f/3.0f) - inner[0];
        float cy = (p0[1]+p1[1]+p2[1]) * (1.0f/3.0f) - inner[1];
        float cz = (p0[2]+p1[2]+p2[2]) * (1.0f/3.0f) - inner[2];
        if (cx*n[0] + cy*n[1] + cz*n[2] < 0.0f) {
            n[0] = -n[0]; n[1] = -n[1]; n[2] = -n[2];
        }
    }
    /* per-facet shading against straight up, not against a sun that moves:
       canopies keep their volume and their lighting follows the clock */
    float upn = n[1] > 0.0f ? n[1] : 0.0f;
    float s = (0.45f + 0.72f * upn) * jitter;
    float col[3] = { base[0]*s, base[1]*s, base[2]*s };
    /* Handed to the shader as a blend of the true facet normal and straight up:
       the true normal alone puts every side face below the ambient floor and the
       tree goes black, and biasing it toward a FIXED sun only worked while the
       sun did not move. Up is the average direction of a round canopy, so it is
       the honest bias now that the light follows the clock. */
    float nv[3] = { n[0]*0.60f, n[1]*0.60f + 0.40f, n[2]*0.60f };
    float nl2 = sqrtf(nv[0]*nv[0] + nv[1]*nv[1] + nv[2]*nv[2]);
    if (nl2 > 1e-6f) { nv[0]/=nl2; nv[1]/=nl2; nv[2]/=nl2; }
    for (int k = 0; k < 3; k++) {
        const float *p = (k == 0) ? p0 : (k == 1) ? p1 : p2;
        /* no sway at the roots, full at the tips, so the canopy bends and the
           trunk base stays planted in the ground */
        float tip = (p[1] - sway_base) / sway_h;
        if (tip < 0.0f) tip = 0.0f;
        if (tip > 1.0f) tip = 1.0f;
        tip = tip * tip * sqrtf(tip);
        push_vert(p, nv, col, tip, sway_phase, 0.0f, 0.0f, sway_bounce);
    }
}

/* Canopy/trunk colours measured off the reference (#758f50 canopy, #706050
   trunk), divided by the shader's constant factor so they land on target. */

/* one green per species, spread in hue as well as value: five shades of the
   same green would read as one species with noise */

/* warm, like the reference sheet's trunks; the old grey-brown vanished into
   the shadow side of the canopy */


/* Jittered grid of candidates, thinned by slope: flat ground keeps almost all
   of them (forests), steep ground almost none. */
/* Water is painted per facet, and a facet is up to ~40 units across while the
   channel is 48 wide, so the painted water spreads a facet radius past the
   shore -- which is why trees used to stand in the middle of lakes. Keep trees
   a facet away from any water instead of testing the point exactly. */
/* Can the ground here hold a river at all? The DEM traces steepest descent,
   and with alpine relief that includes near-vertical drops: carving a bed there
   cuts a notch up a rock face and painting it draws a white cascade. A river
   starts where the ground can hold one, which is also where a spring is. */
int river_bed_ok(float x, float z) {
    float gx = sample_height(x + CELL, z) - sample_height(x - CELL, z);
    float gz = sample_height(x, z + CELL) - sample_height(x, z - CELL);
    float inv = 1.0f / (2.0f * CELL);
    gx *= inv; gz *= inv;
    return gx * gx + gz * gz <= 1.0f;
}

int near_water(float x, float z) {
    /* The margin has to cover the *painted* water, not the mask it is painted
       from. A river facet is now painted when any of its points is in the
       channel, so the visible river reaches half a facet past the centreline
       test -- two cells of margin. A lake is painted by its centroid, so the
       painted edge reaches ~0.7 cell past the mask and a tree one cell out can
       still stand on a painted facet: a tree in the shallows, which is exactly
       the report. Two cells it is. */
    float hw = RIVER_HW_MIN;
    if (river_query(x, z, NULL, NULL, NULL, &hw) < hw + 2.0f * CELL) return 1;
    for (int dz = -2; dz <= 2; dz++)
        for (int dx = -2; dx <= 2; dx++)
            if (lake_at(x + dx * CELL, z + dz * CELL)) return 1;
    /* And a height test, which is the honest one: the water is a plane and a
       tree whose ground is under it is standing in the water, however far the
       nearest lake cell is. The distance test alone left rows of pines basking
       on the shallows where the plane reaches past the mask. */
    {
        float lv = lake_level_near(x, z, 2);
        if (lv > 0.0f && surface_height(x, z) < lv + 0.5f) return 1;
    }
    return 0;
}

/* Rocks: boulders on steep or high ground, scree at the foot of the steep bits,
   sea stacks along exposed coasts. Deterministic from the seed and the cell, so
   a chunk that is rebuilt gets the same rocks back. */
void place_rocks(unsigned seed) {
    enum { RSTEP = 5 };
    for (int gz = 0; gz < N / RSTEP; gz++) {
        for (int gx = 0; gx < N / RSTEP; gx++) {
            unsigned h = terrain_hash(gx, gz, seed ^ 0x2b2b2b1du);
            float r0 = (float)(h & 1023u) / 1023.0f;
            if (r0 > 0.62f) continue;                      /* sparse, but present */
            float x = (gx + ((h >> 10) & 1023u) / 1023.0f) * RSTEP * CELL - TERRAIN_WORLD * 0.5f;
            float z = (gz + ((h >> 20) & 1023u) / 1023.0f) * RSTEP * CELL - TERRAIN_WORLD * 0.5f;
            float y = surface_height(x, z);
            float e = 3.0f * CELL;
            float sx = surface_height(x + e, z) - surface_height(x - e, z);
            float sz = surface_height(x, z + e) - surface_height(x, z - e);
            float slope = sqrtf(sx * sx + sz * sz) / (2.0f * e);
            float r1 = (float)((h >> 4) & 1023u) / 1023.0f;
            float r2 = (float)((h >> 14) & 1023u) / 1023.0f;

            float rh, rr;
            if (y < 2.0f) {
                /* sea stack: only in shallow water, only on an exposed shore, and
                   only where the swell would actually leave one standing */
                if (y < -14.0f) continue;
                if (biome_shelter(x, z) > 0.30f) continue;
                if (r2 > 0.35f) continue;
                rh = 6.0f + 26.0f * r1;
                rr = rh * (0.22f + 0.20f * r2);
                y = 0.0f;
            } else {
                /* boulders and scree: steep ground, or high open ground */
                if (slope < 0.34f && y < 0.30f * peak_y) continue;
                rh = 2.0f + 11.0f * r1 * r1;
                rr = rh * (0.75f + 0.7f * r2);
                if (r2 < 0.30f) { rh *= 0.45f; rr *= 0.75f; }   /* scree chip */
            }
            /* A sea stack standing in the sea is scenery; a rock under a lake's
               surface is not. Height, not distance: the water is a plane. */
            {
                float lv = lake_level_near(x, z, 2);
                if (lv > 0.0f && y < lv + 0.5f) continue;
            }
            if (tree_count >= MAX_TREES) return;
            tree_t *t = &trees[tree_count++];
            t->x = x; t->z = z; t->y = y;
            t->h = rh; t->r = rr;
            t->hash = h;
            t->kind = TREE_ROCK;
        }
    }
}

void place_trees(unsigned seed) {
    /* spacing must exceed the canopy diameter (~0.57 * height) or neighbouring
       trees merge into one silhouette -- the reference shows isolated crowns */
    const float spacing = 20.0f;
    int g = (int)(TERRAIN_WORLD / spacing);
    tree_count = 0;
    for (int gz = 0; gz < g; gz++) {
        for (int gx = 0; gx < g; gx++) {
            if (tree_count >= MAX_TREES) return;
            unsigned h = terrain_hash(gx, gz, seed ^ 0x9e3779b9u);
            float r0 = (float)( h        & 1023u) / 1023.0f;
            float r1 = (float)((h >> 10) & 1023u) / 1023.0f;
            float r2 = (float)((h >> 20) & 1023u) / 1023.0f;
            /* jitter within half a cell: a full-cell jitter lets neighbours
               coincide, which merges crowns into one wide blob */
            float x = (gx + 0.5f + (r0 - 0.5f) * 0.55f) * spacing - TERRAIN_WORLD * 0.5f;
            float z = (gz + 0.5f + (r1 - 0.5f) * 0.55f) * spacing - TERRAIN_WORLD * 0.5f;
            float y = surface_height(x, z);
            /* the treeline follows the summit, not a fixed altitude: a fixed
               one either buries the peak in forest or leaves the lowland bare
               as soon as the amplitude changes. It also follows latitude --
               north is the cold end, and a north-facing hillside loses its
               trees lower down. That is the visible part of "the north". */
            float lat = (z + TERRAIN_WORLD * 0.5f) / TERRAIN_WORLD;
            float treeline = snow_line_at(lat) * 0.52f;
            if (treeline > 0.55f * peak_y) treeline = 0.55f * peak_y;
            if (y < 5.0f || y > treeline) continue;   /* no water, sand or snow */
            if (near_water(x, z)) continue;
            float e = CELL;
            float sx = surface_height(x + e, z) - surface_height(x - e, z);
            float sz = surface_height(x, z + e) - surface_height(x, z - e);
            float slope = sqrtf(sx*sx + sz*sz) / (2.0f * e);   /* tan of the tilt */
            if (slope > 0.90f) continue;
            /* species mix follows altitude: broadleaf and umbrella trees in
               the lowland, firs and spires up toward the treeline -- the
               reference island reads the same way from above */
            float alt = (y - 5.0f) / (treeline - 5.0f);
            if (alt < 0.0f) alt = 0.0f;
            if (alt > 1.0f) alt = 1.0f;
            /* thin out toward the line: a hard edge reads as someone switching
               a forest off halfway up the slope */
            float fade = 1.0f;
            if (alt > 0.62f) {
                fade = 1.0f - (alt - 0.62f) / 0.38f;
                if (fade < 0.0f) fade = 0.0f;
            }
            if (r2 > (0.62f + 0.33f * (1.0f - slope / 0.90f)) * fade) continue;
            unsigned sh = terrain_hash(gx * 3 + 1, gz * 5 + 2, seed ^ 0x2545f491u);
            float sp = (float)((sh >> 8) & 1023u) / 1023.0f;
            float t_fir  = 0.10f + 0.30f * alt;
            float t_spire = t_fir + 0.12f + 0.02f * alt;
            float t_pine = t_spire + 0.42f - 0.25f * alt;
            float t_broad = t_pine + 0.22f - 0.18f * alt;
            if (t_broad > 0.95f) t_broad = 0.95f;
            int kind;
            if (sp < t_fir)        kind = TREE_FIR;
            else if (sp < t_spire) kind = TREE_SPIRE;
            else if (sp < t_pine)  kind = TREE_PINE;
            else if (sp < t_broad) kind = TREE_BROADLEAF;
            else                   kind = TREE_ACACIA;

            tree_t *t = &trees[tree_count++];
            t->x = x; t->z = z; t->y = y;
            t->kind = (unsigned char)kind;
            switch (kind) {
            case TREE_FIR:       t->h = 15.0f + r0 * 12.0f; t->r = 0.16f * t->h; break;
            case TREE_SPIRE:     t->h = 16.0f + r0 * 13.0f; t->r = 0.13f * t->h; break;
            case TREE_BROADLEAF: t->h = 10.0f + r0 *  7.0f; t->r = 0.30f * t->h; break;
            case TREE_ACACIA:    t->h = 12.0f + r0 *  7.0f; t->r = 0.40f * t->h; break;
            default:             t->h = 12.0f + r0 * 12.0f; t->r = 0.22f * t->h; break;
            }
            t->hash = h;
        }
    }
}

/* 6-sided trunk from `by` up `th`. Shared by every species; only the height
   and radius change, which is what makes a bare poplar trunk and a hidden
   conifer trunk cost the same code. */
void emit_trunk(const tree_t *t, float by, float th, float tr) {
    const int SIDES = 6;
    float inner[3] = { t->x, by + th * 0.5f, t->z };
    unsigned h = t->hash;
    for (int s = 0; s < SIDES; s++) {
        float a0 = (float)s * 6.28318531f / SIDES;
        float a1 = (float)(s + 1) * 6.28318531f / SIDES;
        float q[4][3] = {
            { t->x + cosf(a0)*tr, by, t->z + sinf(a0)*tr },
            { t->x + cosf(a1)*tr, by, t->z + sinf(a1)*tr },
            { t->x + cosf(a1)*tr, by + th, t->z + sinf(a1)*tr },
            { t->x + cosf(a0)*tr, by + th, t->z + sinf(a0)*tr },
        };
        float j = 0.93f + 0.14f * facet_hash(s + (int)(h & 4095u));
        emit_tri(q[0], q[1], q[2], inner, TRUNK_COL, j);
        emit_tri(q[0], q[2], q[3], inner, TRUNK_COL, j);
    }
}

/* One conical tier: a lobed rim ring under an apex. Stacked at different
   radii these are the conifer silhouettes. */
void emit_tier(const tree_t *t, float by, float y0, float y1, float rr,
                      float H, const float *col, int k) {
    const int SIDES = 6;
    unsigned h = t->hash;
    float ring[6][3];
    for (int s = 0; s < SIDES; s++) {
        float a = (float)s * 6.28318531f / SIDES + (float)k * 0.55f;
        unsigned jh = terrain_hash(s, k, h);
        float wob = 0.92f + 0.16f * ((jh & 255u) / 255.0f);
        ring[s][0] = t->x + cosf(a) * rr * wob;
        ring[s][1] = y0 + (((jh >> 8) & 127u) / 127.0f - 0.5f) * 0.04f * H;
        ring[s][2] = t->z + sinf(a) * rr * wob;
    }
    float apex[3] = { t->x, y1, t->z };
    float mid[3] = { t->x, (y0 + y1) * 0.5f, t->z };
    for (int s = 0; s < SIDES; s++) {
        int s2 = (s + 1) % SIDES;
        float j = 0.88f + 0.24f * facet_hash((int)(h & 4095u) + k * 8 + s);
        emit_tri(ring[s], ring[s2], apex, mid, col, j);
    }
    (void)by;
}

/* Low-poly blob: two rings plus a pole at each end, 24 flat triangles. This is
   the broadleaf crown, the poplar spire and the umbrella disc -- only the
   radii change, so all three cost one function. */
void emit_blob(const tree_t *t, float cx, float cy, float cz,
                      float rx, float ry, float rz, const float *col, int lobe) {
    const int SIDES = 6;
    const float PHI[3] = { -0.80f, 0.0f, 0.80f };
    float ring[3][6][3];
    for (int b = 0; b < 3; b++) {
        float sy = sinf(PHI[b]), cr = cosf(PHI[b]);
        for (int s = 0; s < SIDES; s++) {
            float a = (float)s * 6.28318531f / SIDES
                    + ((terrain_hash(s, b + lobe, t->hash) & 255u) / 255.0f - 0.5f) * 0.10f;
            float wob = 0.94f + 0.12f * ((terrain_hash(s + 7, b + lobe, t->hash) & 255u) / 255.0f);
            ring[b][s][0] = cx + cosf(a) * rx * cr * wob;
            ring[b][s][1] = cy + sy * ry * wob;
            ring[b][s][2] = cz + sinf(a) * rz * cr * wob;
        }
    }
    float top[3] = { cx, cy + ry, cz };
    float bot[3] = { cx, cy - ry, cz };
    float inner[3] = { cx, cy, cz };
    for (int s = 0; s < SIDES; s++) {
        int s2 = (s + 1) % SIDES;
        float j = 0.90f + 0.20f * facet_hash((int)(t->hash & 2047u) + lobe * 16 + s);
        emit_tri(bot, ring[0][s2], ring[0][s], inner, col, j);       /* underside */
        for (int b = 0; b < 2; b++) {
            emit_tri(ring[b][s], ring[b][s2], ring[b+1][s2], inner, col, j);
            emit_tri(ring[b][s], ring[b+1][s2], ring[b+1][s], inner, col, j);
        }
        emit_tri(ring[2][s], ring[2][s2], top, inner, col, j);       /* crown */
    }
}



/* Boulders and sea stacks, as scenery instances in the tree list: same chunk
   assignment, same snap to the drawn surface, same baked shade. A rock is four
   triangles with a jittered base and an off-centre apex, which at the size these
   appear is the whole difference between "a hillside" and "a hillside with
   scale". They also tell the player where the climbable ground is. */
void emit_rock(const tree_t *t) {
    unsigned h = t->hash;
    float r = t->r, ht = t->h;
    /* Buried nearly half its height: on a cliff a boulder's base ring spans
       twenty units of slope, so a shallow setting shows air under one side. */
    float by = t->y - 0.40f * ht;
    float tint = 0.82f + 0.30f * ((h >> 3) & 255u) / 255.0f;
    float col[3] = { 0.44f * tint, 0.32f * tint, 0.20f * tint };
    float top[3] = { col[0] * 1.18f, col[1] * 1.18f, col[2] * 1.12f };
    float ax = t->x + ((h & 31u) / 31.0f - 0.5f) * r * 0.7f;
    float az = t->z + (((h >> 5) & 31u) / 31.0f - 0.5f) * r * 0.7f;
    sway_base = by - ht;              /* no bend: the whole rock is at "root" */
    sway_h = 1.0f;
    float apex[3] = { ax, by + ht, az };
    float base[4][3];
    for (int k = 0; k < 4; k++) {
        float a = (float)k * 1.5707963f + ((h >> (8 + k * 2)) & 15u) / 15.0f * 0.5f;
        float rr = r * (0.72f + (((h >> (16 + k)) & 15u) / 15.0f) * 0.55f);
        base[k][0] = t->x + cosf(a) * rr;
        base[k][1] = by - 0.15f * ht;
        base[k][2] = t->z + sinf(a) * rr;
    }
    for (int k = 0; k < 4; k++) {
        int k2 = (k + 1) & 3;
        float p0[3] = { base[k][0], base[k][1], base[k][2] };
        float p1[3] = { base[k2][0], base[k2][1], base[k2][2] };
        /* The last argument multiplies the colour: 0.12 painted every boulder
           at 12% brightness, i.e. black holes on a sunlit cliff. */
        float j = 0.92f + 0.16f * facet_hash((int)(h & 4095u) + k);
        emit_tri(p0, apex, p1, apex, k & 1 ? col : top, j);
    }
}

void emit_tree(const tree_t *t) {
    float H = t->h;
    unsigned h = t->hash;
    float by = t->y - 2.5f;            /* sunk: grid skew/jitter can lift the mesh */
    float tint = 0.86f + 0.28f * ((h & 255u) / 255.0f);   /* per-tree variation */
    if (t->kind == TREE_ROCK) { emit_rock(t); return; }
    const float *base = LEAF_COL;
    switch (t->kind) {
    case TREE_FIR:       base = FIR_COL;       break;
    case TREE_SPIRE:     base = SPIRE_COL;     break;
    case TREE_BROADLEAF: base = BROADLEAF_COL; break;
    case TREE_ACACIA:    base = ACACIA_COL;    break;
    default: break;
    }
    float leaf[3] = { base[0]*tint, base[1]*tint, base[2]*tint };
    sway_base = by;
    sway_h = H * 1.02f;
    sway_phase = (float)((h >> 8) & 1023u) / 1023.0f;
    /* Far trees are a few pixels across, and they are 92% of the vertex
       stream. One tier instead of three to five, same shading path so they
       still take the baked shadow and sway. ponytail: one silhouette for all
       species -- at this distance none of the difference lands on a pixel. */
    if (tree_detail) {
        emit_tier(t, by, by + H * 0.18f, by + H, t->r * 1.30f, H, leaf, 0);
        return;
    }

    /* three overlapping conical skirts with a lobed rim: a cone silhouette
       with visible tiers reads as pine at any size, a smooth egg reads as blob */
    static const float PINE_BASE[3] = { 0.16f, 0.42f, 0.66f };
    static const float PINE_R[3]    = { 1.00f, 0.72f, 0.44f };
    static const float PINE_TOP[3]  = { 0.56f, 0.80f, 1.00f };
    /* slender conifer: four tighter plates on a taller trunk */
    static const float FIR_BASE[4]  = { 0.12f, 0.34f, 0.55f, 0.74f };
    static const float FIR_R[4]     = { 1.00f, 0.80f, 0.58f, 0.32f };
    static const float FIR_TOP[4]   = { 0.42f, 0.62f, 0.82f, 1.00f };
    const float TIER[4] = { 0.84f, 0.93f, 1.02f, 1.10f };

    switch (t->kind) {
    case TREE_PINE:
        emit_trunk(t, by, H * 0.20f, t->r * 0.14f);
        for (int k = 0; k < 3; k++) {
            float tc = TIER[k];
            float lc[3] = { leaf[0]*tc, leaf[1]*tc, leaf[2]*tc };
            emit_tier(t, by, by + PINE_BASE[k]*H, by + PINE_TOP[k]*H,
                      t->r * PINE_R[k], H, lc, k);
        }
        break;

    case TREE_FIR:
        emit_trunk(t, by, H * 0.16f, t->r * 0.15f);
        for (int k = 0; k < 4; k++) {
            float tc = TIER[k];
            float lc[3] = { leaf[0]*tc, leaf[1]*tc, leaf[2]*tc };
            emit_tier(t, by, by + FIR_BASE[k]*H, by + FIR_TOP[k]*H,
                      t->r * FIR_R[k], H, lc, k);
        }
        break;

    case TREE_SPIRE: {
        /* tall narrow crown on a bare trunk: the sheet's poplar. ry carries
           the height, so the trunk stays visible underneath */
        float th = H * 0.38f;
        emit_trunk(t, by, th, t->r * 0.16f);
        float ry = H * 0.30f;
        emit_blob(t, t->x, by + th + ry * 0.85f, t->z,
                  t->r, ry, t->r * 0.85f, leaf, 0);
        break;
    }

    case TREE_BROADLEAF: {
        float th = H * 0.42f;
        emit_trunk(t, by, th, t->r * 0.19f);
        float ry = t->r * 1.15f;
        emit_blob(t, t->x, by + th + ry * 0.80f, t->z, t->r, ry, t->r, leaf, 0);
        break;
    }

    case TREE_ACACIA:
        /* flat umbrella disc over a thick short trunk, plus one offset lobe so
           the crown is not a symmetrical mushroom */
        emit_trunk(t, by, H * 0.52f, t->r * 0.22f);
        {
            float ry = t->r * 0.42f;
            float cy = by + H * 0.52f + ry * 0.9f;
            emit_blob(t, t->x, cy, t->z, t->r * 1.20f, ry, t->r, leaf, 0);
            emit_blob(t, t->x + t->r * 0.55f, cy + ry * 0.9f, t->z - t->r * 0.35f,
                      t->r * 0.62f, ry * 0.75f, t->r * 0.58f, leaf, 1);
        }
        break;

    default:
        break;
    }
}

/* Clouds are lit flat, with one upward normal and a per-facet jitter, instead
   of per-facet normals: real normals turn the undersides into rock. */
void emit_flat_tri(const float *p0, const float *p1, const float *p2,
                          const float *base, float jitter, float phase) {
    float c[3] = { base[0]*jitter, base[1]*jitter, base[2]*jitter };
    for (int k = 0; k < 3; k++) {
        const float *p = (k == 0) ? p0 : (k == 1) ? p1 : p2;
        /* negative weight: the vertex shader drifts these instead of swaying */
        const float cup[3] = { 0.0f, 1.0f, 0.0f };
        push_vert(p, cup, c, -1.0f, phase, 0.0f, 0.0f, NULL);
    }
}

/* Low-poly cloud: a cluster of squashed 6-sided ellipsoids. Same emit_tri path
   as everything else, so clouds cost no extra pipeline and shade with the same
   sun -- which is what makes them read as faceted volumes instead of sprites. */
void emit_cloud(unsigned seed) {
    const int NCLOUDS = 4, LOBES = 5;
    for (int c = 0; c < NCLOUDS; c++) {
        unsigned ch = terrain_hash(c, 91, seed);
        /* inside the view cone: clouds scattered over the whole island were
           almost never in frame */
        float ang = yaw + (((float)(ch & 1023u) / 1023.0f) - 0.5f) * 1.6f;
        float rad = (0.55f + 0.30f * (float)((ch >> 10) & 1023u) / 1023.0f) * TERRAIN_WORLD;
        float cx = cosf(ang) * rad;
        float cz = sinf(ang) * rad;
        float cy = peak_y * (1.25f + 0.45f * (float)((ch >> 20) & 255u) / 255.0f);
        float size = 34.0f + 26.0f * (float)((ch >> 4) & 255u) / 255.0f;
        float phase = (float)((ch >> 16) & 255u) / 255.0f;
        for (int l = 0; l < LOBES; l++) {
            unsigned lh = terrain_hash(c * 17 + l, 7, seed);
            float ox = ((float)(lh & 255u) / 255.0f - 0.5f) * 2.2f * size;
            float oz = ((float)((lh >> 8) & 255u) / 255.0f - 0.5f) * size;
            float rx = size * (0.6f + 0.5f * (float)((lh >> 16) & 127u) / 127.0f);
            float ry = rx * 0.55f;
            float rz = rx * 0.85f;
            const float col[3] = { 0.97f, 0.95f, 0.90f };
            /* 6 sides x 5 bands, closed near the pole: rings must line up
               (no per-band rotation) or the quads twist into streaks */
            float mid[3] = { cx + ox, cy, cz + oz };
            const float PHI[5] = { -0.70f, -0.28f, 0.14f, 0.55f, 1.25f };
            float band[5][6][3];
            for (int b = 0; b < 5; b++) {
                float sy = sinf(PHI[b]), cr = cosf(PHI[b]);
                for (int sd = 0; sd < 6; sd++) {
                    float a = (float)sd * 6.28318531f / 6.0f;
                    band[b][sd][0] = mid[0] + cosf(a) * rx * cr;
                    band[b][sd][1] = mid[1] + sy * ry;
                    band[b][sd][2] = mid[2] + sinf(a) * rz * cr;
                }
            }
            for (int b = 0; b < 4; b++)
                for (int sd = 0; sd < 6; sd++) {
                    int s2 = (sd + 1) % 6;
                    float j = 0.93f + 0.13f * facet_hash(c * 64 + l * 8 + b);
                    emit_flat_tri(band[b][sd], band[b][s2], band[b+1][s2], col, j, phase);
                    emit_flat_tri(band[b][sd], band[b+1][s2], band[b+1][sd], col, j, phase);
                }
        }
    }
}

/* One cheap runnable check: a tree that floats, sinks, or goes NaN is the
   failure mode of the placement maths, and it is invisible in a screenshot. */
void trees_selfcheck(void) {
    for (int i = 0; i < tree_count; i++) {
        assert(trees[i].h > 0.0f && trees[i].r > 0.0f);
        if (trees[i].kind == TREE_ROCK) {
            /* sea stacks stand in the water with their base below it */
            assert(trees[i].y >= 0.0f || trees[i].y < -1.0f);
            continue;
        }
        assert(trees[i].y > 0.0f);
        assert(fabsf(trees[i].y - surface_height(trees[i].x, trees[i].z)) < 1e-3f);
    }
}

void pick_camera(void);

/* A tree in the first frame's lens reads as a bug, so drop the ones the camera
   stands among. Swap-remove; order does not matter. */
void clear_start_clearing(void) {
    const float r2 = 18.0f * 18.0f;
    float vx = peak_x - cam_x, vz = peak_z - cam_z;
    float len = sqrtf(vx * vx + vz * vz);
    if (len > 1.0f) { vx /= len; vz /= len; }
    float corridor = 0.45f * len;      /* keep midground forest, clear the view */
    for (int i = 0; i < tree_count; ) {
        float dx = trees[i].x - cam_x, dz = trees[i].z - cam_z;
        float along = dx * vx + dz * vz;
        float side = fabsf(dx * vz - dz * vx);   /* perpendicular distance */
        bool near_cam = dx * dx + dz * dz < r2;
        bool in_corridor = along > 0.0f && along < corridor && side < 16.0f;
        if (near_cam || in_corridor) trees[i] = trees[--tree_count];
        else i++;
    }
}

/* Flat water at y = 0. Before this the sea was just terrain painted teal, so
   the coast read as oddly coloured dirt. Opaque, no waves: the reference is a
   flat colour with a hard shoreline, and the fog does the distance work. */
void emit_flat_up(const float *p0, const float *p1, const float *p2,
                         const float *c, float fx, float fz) {
    const float up[3] = { 0.0f, 1.0f, 0.0f };
    for (int k = 0; k < 3; k++) {
        const float *p = (k == 0) ? p0 : (k == 1) ? p1 : p2;
        push_vert(p, up, c, -2.0f, 0.0f, fx, fz, NULL);   /* -2: water */
    }
}

/* Birds: a two-triangle V each, flown entirely in the vertex shader -- the
   flock circles on the clock, which keeps the scene one draw call and keeps
   --shot reproducible. Placed once around the summit, at altitudes where a
   silhouette reads against the sky and not against the rock. */
void emit_birds(unsigned seed) {
    static const float BIRD_COL[3] = { 0.17f, 0.16f, 0.15f };
    const float up[3] = { 0.0f, 1.0f, 0.0f };
    for (int i = 0; i < 11; i++) {
        unsigned h = terrain_hash(i, 77, seed ^ 0x51ed270bu);
        float ang = (float)(h & 1023u) / 1023.0f * 6.28318531f;
        float rad = TERRAIN_WORLD * (0.10f + 0.06f * (float)((h >> 10) & 255u) / 255.0f);
        float y   = peak_y * (0.55f + 0.32f * (float)((h >> 18) & 255u) / 255.0f);
        float sz  = 1.7f + 1.3f * (float)((h >> 26) & 63u) / 63.0f;
        float ph  = (float)((h >> 4) & 255u) / 255.0f;
        float bx = peak_x + cosf(ang) * rad, bz = peak_z + sinf(ang) * rad;
        float v[6][3] = {
            { bx,          y, bz + sz*0.55f },   /* nose  */
            { bx - sz,     y, bz - sz*0.45f },   /* tip   */
            { bx - sz*0.30f, y, bz - sz*0.10f }, /* inner */
            { bx,          y, bz + sz*0.55f },
            { bx + sz*0.30f, y, bz - sz*0.10f },
            { bx + sz,     y, bz - sz*0.45f },
        };
        for (int k = 0; k < 6; k++)
            push_vert(v[k], up, BIRD_COL, 3.0f, ph, v[k][0] - bx, 0.0f, NULL);
    }
}

void emit_water(void) {
    /* well past the terrain: a plane that stops at the world edge shows the
       sky through the gap where the sea meets the horizon.
       One quad, not a grid. The grid existed to shade each panel separately,
       and the water shader now reflects the sky instead, so the subdivision
       bought nothing -- while its quad count grew with the world and could
       overflow the decor vertex buffer. */
    const float ext = SEA_EXTENT;
    const float y = 0.0f;
    float q[4][3] = { { -ext, y, -ext }, { ext, y, -ext },
                      {  ext, y,  ext }, { -ext, y,  ext } };
    float c[3] = { WATER_COL[0], WATER_COL[1], WATER_COL[2] };
    emit_flat_up(q[0], q[1], q[2], c, 0.0f, 0.0f);
    emit_flat_up(q[0], q[2], q[3], c, 0.0f, 0.0f);
}

/* ------------------------------------------------------------- planar mesh
   The terrain is not drawn on the grid it is sampled on. A variable-density
   point set follows the shape (dense on the massif, sparse on the meadow),
   Delaunay-triangulates it, and coplanar neighbours are merged into one facet
   colour. Irregular polygons with straight edges instead of a lattice, and the
   triangles land where the shape is instead of everywhere equally. */

/* --- per-chunk mesh -------------------------------------------------------
   Each chunk is triangulated on its own, from points generated inside its own
   rectangle. That is what makes build cost a function of the chunk instead of
   the world: the global Delaunay was O(n^2) over every point on the map, so a
   continental world was seconds of startup however the threading was arranged.

   Neighbours meet without a crack because the border ring is generated with no
   jitter and at full resolution whatever the LOD, so both sides of a shared
   border produce the identical chain of points there and their hull edges
   match exactly. Only the interior coarsens with distance, which is why there
   are no skirts here. */

/* ground shadow and bounced light per point, filled right after the point set
   is final */



static dtri_t dt[MAX_DT];


/* Bowyer-Watson creates a triangle for every edge of the cavity it re-cuts, so
   the *cumulative* count is several times the number of triangles that survive;
   this used to be a fixed array indexed by that cumulative count, and a dense
   chunk (a river mouth inside a lake, seen from a metre away) silently ran out
   of slots. Everything past the cap was dropped, so the nearest chunks -- the
   only ones the player ever stands in -- lost facets and showed the bed, the sea
   plane and sky through the holes. Dead slots are recycled instead: the array is
   then the size of the live triangulation (~2n) and cannot overflow in practice. */
static int dt_free = -1;

void dt_add(int a, int b, int c) {
    int slot;
    if (dt_free >= 0) { slot = dt_free; dt_free = dt[slot].v[0]; }
    else if (ndt < MAX_DT) slot = ndt++;
    else { tri_overflow++; return; }
    dtri_t *t = &dt[slot];
    t->v[0] = a; t->v[1] = b; t->v[2] = c; t->alive = 1; t->r2 = -1.0f;
    float ax = pts_x[a], az = pts_z[a];
    float bx = pts_x[b], bz = pts_z[b];
    float cx = pts_x[c], cz = pts_z[c];
    float d = 2.0f * (ax*(bz-cz) + bx*(cz-az) + cx*(az-bz));
    if (fabsf(d) < 1e-6f) { t->alive = 0; return; }     /* degenerate */
    float a2 = ax*ax+az*az, b2 = bx*bx+bz*bz, c2 = cx*cx+cz*cz;
    t->cx = (a2*(bz-cz) + b2*(cz-az) + c2*(az-bz)) / d;
    t->cz = (a2*(cx-bx) + b2*(ax-cx) + c2*(bx-ax)) / d;
    float dx = t->cx - ax, dz = t->cz - az;
    t->r2 = dx*dx + dz*dz;
}

/* Bowyer-Watson, O(n^2) in the triangle scan. Per chunk that is ~200 points,
   i.e. a fraction of a millisecond, and it stays that size whatever the world
   is -- which is the entire point of triangulating per chunk. */
void delaunay(void) {
    int n = npts;
    pts_x[n] = -30000.0f; pts_z[n] = -30000.0f;
    pts_x[n+1] = 30000.0f; pts_z[n+1] = -30000.0f;
    pts_x[n+2] = 0.0f;     pts_z[n+2] = 30000.0f;
    ndt = 0;
    dt_free = -1;
    dt_add(n, n+1, n+2);
    static int ea[MAX_DT * 3], eb[MAX_DT * 3];
    for (int i = 0; i < n; i++) {
        int ne = 0;
        for (int k = 0; k < ndt; k++) {
            if (!dt[k].alive) continue;
            float dx = pts_x[i] - dt[k].cx, dz = pts_z[i] - dt[k].cz;
            if (dx*dx + dz*dz >= dt[k].r2 - 1e-3f) continue;
            for (int e = 0; e < 3; e++) {
                int a = dt[k].v[e], b = dt[k].v[(e+1) % 3];
                int found = -1;                       /* shared edge: cancel */
                for (int q = 0; q < ne; q++)
                    if (ea[q] == b && eb[q] == a) { found = q; break; }
                if (found >= 0) {
                    ea[found] = ea[--ne]; eb[found] = eb[ne];
                } else {
                    ea[ne] = a; eb[ne] = b; ne++;
                }
            }
            /* recycle the slot, but only after its edges have been read out */
            dt[k].alive = 0;
            dt[k].v[0] = dt_free;
            dt_free = k;
        }
        for (int q = 0; q < ne; q++) dt_add(ea[q], eb[q], i);
    }
    for (int k = 0; k < ndt; k++)
        if (dt[k].alive && (dt[k].v[0] >= n || dt[k].v[1] >= n || dt[k].v[2] >= n))
            dt[k].alive = 0;
}

/* A boundary point remembers which side(s) of the chunk rect it sits on, so
   the emitter can find the boundary edges that need a skirt. */


/* --- point sampling ------------------------------------------------------ */
/* Every point must land inside the chunk being built. A point outside the rect
   (a river bank one cell over, say) extends the convex hull beyond the chunk
   and Delaunay fans it back to the nearest border run -- a handful of slivers
   200 units long, which is exactly what that looked like on screen. */

void add_point(float x, float z, float min_d);

/* A point on a chunk's border ring. It is marked explicitly, because the mark
   used to be inferred from being within 0.05 units of the rect edge and the ring
   is deliberately not straight (see ring_off). */
void add_edge_point(float x, float z, unsigned bits) {
    int before = npts;
    add_point(x, z, 0.01f);
    if (npts > before) pt_edge[before] |= (unsigned char)bits;
}

/* How far a border point sits off the straight line, +-1.5 units.
   The ring used to be a run of exactly collinear points on the cell lattice,
   and a collinear run is degenerate for the circumcircle test: the fill left
   some of them out and bridged the gap with a facet 100-150 units long -- the
   sand wedges and the dark shards, and (because its colour and its water class
   are each decided once) a facet that is bluff on one corner and seabed on
   another. Offsetting each point breaks the degeneracy without moving the chain
   off the border in any way the neighbour can disagree about: the offset is a
   hash of the point's own *world* cell indices and is always applied along the
   same world axis, so the chunk on the other side computes the same point. */
float ring_off(int ci, int cj) {
    unsigned h = terrain_hash(ci, cj, terrain_seed ^ 0x7a3d91u);
    /* Just under the half unit a point may sit outside the chunk rect (see
       add_point's clip): the two chunks that share a border must both keep the
       point, or one of them draws a chord the other does not. A larger offset
       would decorrelate the fill better and crack every seam. */
    return ((float)(h & 255u) / 255.0f - 0.5f) * 0.9f;
}

void add_point(float x, float z, float min_d) {
    if (npts >= MAX_PTS) { pt_overflow++; return; }
    if (x < clip_x0 - 0.5f || x > clip_x1 + 0.5f) return;
    if (z < clip_z0 - 0.5f || z > clip_z1 + 0.5f) return;
    /* the jitter can push a border point off the heightfield: sampling there
       returns the out-of-grid sentinel and the triangle would spike to -1e9 */
    if (sample_height(x, z) < -1e8f) return;
    for (int i = 0; i < npts; i++) {
        float dx = pts_x[i] - x, dz = pts_z[i] - z;
        if (dx*dx + dz*dz < min_d*min_d) return;
    }
    unsigned char e = 0;
    if (x <= clip_x0 + 0.05f) e |= 1u;
    if (x >= clip_x1 - 0.05f) e |= 2u;
    if (z <= clip_z0 + 0.05f) e |= 4u;
    if (z >= clip_z1 - 0.05f) e |= 8u;
    pts_x[npts] = x; pts_z[npts] = z; pt_edge[npts] = e; npts++;
}

/* Height, colour and lighting are all sampled at the facet centroid: one value
   per polygon is what makes neighbouring coplanar triangles read as a single
   plane instead of a pair. */




int chunk_of(float x, float z) {
    int cx = (int)((x + TERRAIN_WORLD * 0.5f) / CHUNK_WORLD);
    int cz = (int)((z + TERRAIN_WORLD * 0.5f) / CHUNK_WORLD);
    if (cx < 0) cx = 0; if (cx >= CHUNK_GRID) cx = CHUNK_GRID - 1;
    if (cz < 0) cz = 0; if (cz >= CHUNK_GRID) cz = CHUNK_GRID - 1;
    return cz * CHUNK_GRID + cx;
}

/* One shade step per facet plane. This used to be a hash of the coplanar
   cluster id, which cannot work per chunk: two coplanar triangles either side
   of a chunk border would get different shades and the ground would be ruled
   with a 181-unit grid of colour breaks. Keying on the plane plus a coarse
   position cell makes the shade a function of world position only, so the
   border disappears and the block size stays the same as the old cluster cap gave. */
float facet_shade(float nx, float ny, float nz, float off, float x, float z) {
    int qx = (int)floorf(nx * 10.0f), qy = (int)floorf(ny * 10.0f), qz = (int)floorf(nz * 10.0f);
    int qo = (int)floorf(off * 0.5f);
    int gx = (int)floorf(x / 47.0f), gz = (int)floorf(z / 47.0f);
    unsigned h = (unsigned)qx * 73856093u ^ (unsigned)qy * 19349663u
               ^ (unsigned)qz * 83492791u ^ (unsigned)qo * 2654435761u
               ^ (unsigned)gx * 15485863u ^ (unsigned)gz * 32452843u;
    return (float)(h & 255u) / 255.0f;
}

/* Build one chunk from scratch and return its vertex word count. Runs on the
   builder thread; chunk_verts is this thread's scratch. */
/* Emit a convex polygon (already in x, z with a per-point y) as a triangle
   fan. The water and the bed are both emitted through this, on the same
   polygon, so their common edge cannot disagree. */
/* The baked ground colour at a world position, bilinearly. It used to be
   inlined once, at a facet's centre; a facet has three corners and they can be
   a hundred units apart, so the centre is not a sample *of* the facet when the
   facet spans the shore or a ridge. That is what painted a navy plate on an
   island and meadow green on a rock face. */
static void ground_colour_at(const float *cr, const float *cg, const float *cb,
                             float x, float z, float out[3]) {
    float gx = (x + TERRAIN_WORLD * 0.5f) / CELL;
    float gz = (z + TERRAIN_WORLD * 0.5f) / CELL;
    int x0 = (int)floorf(gx), z0 = (int)floorf(gz);
    if (x0 < 0) x0 = 0; if (x0 > N-2) x0 = N-2;
    if (z0 < 0) z0 = 0; if (z0 > N-2) z0 = N-2;
    float fx = gx - x0, fz = gz - z0;
    if (fx < 0.0f) fx = 0.0f; if (fx > 1.0f) fx = 1.0f;
    if (fz < 0.0f) fz = 0.0f; if (fz > 1.0f) fz = 1.0f;
    const int i00 = z0*N+x0, i10 = i00+1, i01 = i00+N, i11 = i01+1;
    #define BIL(arr) (((arr[i00]*(1-fx)+arr[i10]*fx))*(1-fz) \
                    + ((arr[i01]*(1-fx)+arr[i11]*fx))*fz)
    out[0] = BIL(cr); out[1] = BIL(cg); out[2] = BIL(cb);
    #undef BIL
}

/* kind: 0 for a solid (bed, rock), 1 for still water, 2 for falling water.
   A water polygon must *say* it is water, in anim.x, rather than having it
   inferred from a non-zero flow vector: a fall whose nearest river segment is
   degenerate has no flow direction at all, and it was then shaded as terrain --
   a flat pale ribbon lying on the rock. anim.x = -2 is the marker emit_flat_up
   already uses for the sea, and anim.y (the tree sway phase, unused here) says
   which kind of water it is. */
static void emit_fan(int nv, const float xz[5][2], const float *y, const float *nrm,
                     const float *col, float fx, float fz, const float *bc,
                     float kind) {
    const float aw = kind > 0.5f ? -2.0f : 0.0f;
    for (int t = 1; t + 1 < nv; t++) {
        float a[3] = { xz[0][0],  y[0],  xz[0][1]  };
        float b[3] = { xz[t][0],  y[t],  xz[t][1]  };
        float c[3] = { xz[t+1][0], y[t+1], xz[t+1][1] };
        push_vert(a, nrm, col, aw, kind, fx, fz, bc);
        push_vert(b, nrm, col, aw, kind, fx, fz, bc);
        push_vert(c, nrm, col, aw, kind, fx, fz, bc);
    }
}

/* --- is this class even visible? -------------------------------------------
   A counter says how many facets of a class exist; it says nothing about
   whether a player can see one. V_CLASS=tiny|seam|dark|fall paints that class
   magenta so tools/visible.sh can count its pixels -- the same instrument P3/P4
   used by hand, kept. It is a diagnostic: with the variable unset this compiles
   to one predictable branch per facet and nothing else. */
static const float vis_magenta[3] = { 1.0f, 0.0f, 1.0f };
static int vis_class;
static int vis_init;
/* PICK=x,y: print the facet the renderer draws at that pixel. PICK_PAINT=1
   paints it, so the answer can be checked against the picture. */
static int pick_x = -1, pick_y = -1, pick_init, pick_paint;
static unsigned char pick_hit[MAX_DT];
static void pick_setup(void) {
    const char *pk = getenv("PICK");
    pick_init = 1;
    if (pk) sscanf(pk, "%d,%d", &pick_x, &pick_y);
    pick_paint = getenv("PICK_PAINT") != NULL;
    if (pick_x >= 0)
        fprintf(stderr, "PICK %d,%d  viewport %dx%d  cam %.1f,%.1f,%.1f\n",
                pick_x, pick_y, gfx_w, gfx_h, (double)cam_x, (double)cam_y, (double)cam_z);
}
static int vis_match(int cls, int k, int step) {
    if (cls == 3) return tri_gerr[k] > 1.0f;              /* dark: a chord */
    if (cls == 4) return tri_wet[k] == 2;                 /* fall: foam reach */
    /* tiny and seam reproduce the counter's own tests, on the facet as built */
    const int v[3] = { dt[k].v[0], dt[k].v[1], dt[k].v[2] };
    float ax = pts_x[v[0]], az = pts_z[v[0]];
    float ar = 0.5f * fabsf((pts_x[v[1]] - ax) * (pts_z[v[2]] - az)
                          - (pts_z[v[1]] - az) * (pts_x[v[2]] - ax));
    float best = 0.0f;
    for (int e = 0; e < 3; e++) {
        int pa = v[e], pb = v[(e + 1) % 3];
        float dx = pts_x[pb] - pts_x[pa], dz = pts_z[pb] - pts_z[pa];
        float l = sqrtf(dx*dx + dz*dz);
        if (l > best) best = l;
        if (cls == 2 && l > 1.5f * (float)CELL && (pt_edge[pa] & pt_edge[pb]) != 0) {
            float dev = sample_height((pts_x[pa] + pts_x[pb]) * 0.5f,
                                      (pts_z[pa] + pts_z[pb]) * 0.5f)
                      - 0.5f * (sample_height(pts_x[pa], pts_z[pa])
                              + sample_height(pts_x[pb], pts_z[pb]));
            if (dev < 0.0f) dev = -dev;
            if (dev > 1.0f) return 1;
        }
    }
    (void)step;
    return cls == 1 && best > 0.0f && 2.0f * ar / best < 1.0f;
}

int chunk_build(int ci, int step, unsigned seed, const float *cr,
                       const float *cg, const float *cb) {
    if (!pick_init) pick_setup();
    if (!vis_init) {
        const char *v = getenv("V_CLASS");
        vis_init = 1;
        if (v && !strcmp(v, "tiny")) vis_class = 1;
        else if (v && !strcmp(v, "seam")) vis_class = 2;
        else if (v && !strcmp(v, "dark")) vis_class = 3;
        else if (v && !strcmp(v, "fall")) vis_class = 4;
    }
    const int cx = chunks[ci].cx, cz = chunks[ci].cz;
    const int c0 = cx * CHUNK_CELLS, r0 = cz * CHUNK_CELLS;
    int c1 = c0 + CHUNK_CELLS, r1 = r0 + CHUNK_CELLS;
    if (c1 > N - 1) c1 = N - 1;          /* the last column/row is short */
    if (r1 > N - 1) r1 = N - 1;
    if (c1 <= c0 || r1 <= r0) return 0;  /* chunk entirely past the world edge */
    const float ox = c0 * CELL - TERRAIN_WORLD * 0.5f;
    const float oz = r0 * CELL - TERRAIN_WORLD * 0.5f;
    const float ex = c1 * CELL - TERRAIN_WORLD * 0.5f;
    const float ez = r1 * CELL - TERRAIN_WORLD * 0.5f;
    tree_detail = step > 2;

    clip_x0 = ox; clip_x1 = ex; clip_z0 = oz; clip_z1 = ez;
    npts = 0;
    /* Border ring first, unjittered and at full resolution: the neighbour
       generates exactly these points along the same line, so the two chunk
       surfaces share a vertex chain and cannot crack or overlap. */
    /* The four corners are exactly on the lattice and never offset, and every
       side skips them: a corner reached from two sides would otherwise be added
       twice, a unit or two apart, and leave a sliver at every corner. */
    for (int k = c0; k <= c1; k += step) {
        float f = k * CELL - TERRAIN_WORLD * 0.5f;
        if (k == c0 || k == c1) continue;
        add_edge_point(f, oz + ring_off(k, r0), 4u);
        add_edge_point(f, ez + ring_off(k, r1), 8u);
    }
    for (int k = r0; k <= r1; k += step) {
        float f = k * CELL - TERRAIN_WORLD * 0.5f;
        if (k == r0 || k == r1) continue;
        add_edge_point(ox + ring_off(c0, k), f, 1u);
        add_edge_point(ex + ring_off(c1, k), f, 2u);
    }
    add_edge_point(ox, oz, 5u);
    add_edge_point(ex, oz, 6u);
    add_edge_point(ox, ez, 9u);
    add_edge_point(ex, ez, 10u);
    /* River first among the interior, for the same reason as before: vertices
       on both banks make the water edge a crease in the mesh instead of a
       facet that merely straddles the channel. */
    for (int i = 0; i < seg_n; i++) {
        float dx = seg_x1[i] - seg_x0[i], dz = seg_z1[i] - seg_z0[i];
        float l = sqrtf(dx*dx + dz*dz);
        if (l < 1e-4f) continue;
        float px = -dz / l, pz = dx / l;
        float hw = seg_hw[i];
        add_point(seg_x0[i] + px * hw, seg_z0[i] + pz * hw, 9.0f);
        add_point(seg_x0[i] - px * hw, seg_z0[i] - pz * hw, 9.0f);
        add_point(seg_x1[i] + px * hw, seg_z1[i] + pz * hw, 9.0f);
        add_point(seg_x1[i] - px * hw, seg_z1[i] - pz * hw, 9.0f);
    }
    for (int zi = r0 + step; zi < r1; zi += step) {
        for (int xi = c0 + step; xi < c1; xi += step) {
            int xm = xi > 0 ? xi-1 : xi, xp = xi < N-1 ? xi+1 : xi;
            int zm = zi > 0 ? zi-1 : zi, zp = zi < N-1 ? zi+1 : zi;
            float dhdx = (heights[zi*N+xp] - heights[zi*N+xm]) / ((xp-xm) * CELL);
            float dhdz = (heights[zp*N+xi] - heights[zm*N+xi]) / ((zp-zm) * CELL);
            float slope = sqrtf(dhdx*dhdx + dhdz*dhdz);
            float h = heights[zi*N+xi];
            /* spacing from steepness: the massif is where the shape lives */
            float t = slope / 0.55f;
            if (t > 1.0f) t = 1.0f;
            float d = 36.0f - 25.0f * t;
            if (fabsf(h) < 12.0f) d = fminf(d, 15.0f);   /* keep the shoreline readable */
            /* LOD wins over the slope rule, or the interior would not cost less */
            float floor_d = (float)step * CELL * 0.95f;
            if (d < floor_d) d = floor_d;
            /* jitter the candidate so the set does not inherit the lattice */
            unsigned hs = terrain_hash(xi, zi, seed ^ 0x68e31da4u);
            float jx = ((float)( hs        & 255u) / 255.0f - 0.5f) * CELL * 0.9f * step;
            float jz = ((float)((hs >> 8)  & 255u) / 255.0f - 0.5f) * CELL * 0.9f * step;
            float x = xi * CELL - TERRAIN_WORLD * 0.5f + jx;
            float z = zi * CELL - TERRAIN_WORLD * 0.5f + jz;
            if (x < ox + 0.5f || x > ex - 0.5f || z < oz + 0.5f || z > ez - 0.5f) continue;
            add_point(x, z, d);
        }
    }
    /* The horizon comes from the world's field, not from this chunk's points:
       see bake_horizon_grid. Only the bounce is per point, because it is a
       colour of the ground here rather than a shadow of the ground behind. */
    for (int i = 0; i < npts; i++) {
        float py = sample_height(pts_x[i], pts_z[i]);
        bounce_at(pts_x[i], pts_z[i], py, cr, cg, cb, bnc_pt[i]);
    }
    /* Refine the fill before anything is coloured. A facet whose edge is much
       longer than this tier's spacing is one the point set left a gap under --
       the border ring's empty band, or a dedupe radius larger than the spacing
       -- and the triangulation spans it with a chord: a facet can bridge a
       cliff top to a wall 100 units below, or a plateau to the sea, taking its
       colour from one centre sample and its geometry from three unrelated
       places. That is the green wedge on a rock face and the sea-coloured plate
       lying on an island. Splitting such an edge and re-triangulating is cheap
       (only a minority of facets), keeps the shared border chain untouched, and
       fixes colour, water class and normal together, because the new points are
       sampled like every other point. */
    {
        const float lim = 3.0f * (float)step * CELL;
        delaunay();
        for (int pass = 0; pass < 2; pass++) {
            int added = 0;
            for (int k = 0; k < ndt && npts < MAX_PTS - 8; k++) {
                if (!dt[k].alive) continue;
                for (int e = 0; e < 3; e++) {
                    int a = dt[k].v[e], b = dt[k].v[(e + 1) % 3];
                    /* A border point anywhere on the edge means the edge may be
                       part of a chain the neighbour also has, so it is left
                       alone. (Splitting when only *one* endpoint is a border
                       point is legal, but measured: +20% points and +150ms of
                       build for `seamgap` 135 -> 121 and nothing on screen, so
                       the conservative rule stays.) */
                    if (pt_edge[a] || pt_edge[b]) continue;
                    float dx = pts_x[a] - pts_x[b], dz = pts_z[a] - pts_z[b];
                    if (dx*dx + dz*dz < lim * lim) continue;
                    int before = npts;
                    add_point((pts_x[a] + pts_x[b]) * 0.5f,
                              (pts_z[a] + pts_z[b]) * 0.5f, 1.0f);
                    if (npts > before) added++;
                }
            }
            if (!added) break;
            delaunay();
        }
    }

    /* --- weld the points the triangulation left out -------------------------
       Bowyer-Watson rejects a near-collinear triple (d < 1e-6 in dt_add), and a
       point whose whole cavity turns out to be such triples is inserted into
       nothing: it stays in the point set, no facet uses it, and the fill spans
       the hole it was placed to describe. That is how a facet 220 units long
       ends up with another point 6 units from its own midpoint -- the sample was
       there, the triangulation just did not see it -- and it is why refining by
       error kept adding points without making the worst facet any better.
       Repair is cheap and exact: an unused point must lie inside some facet
       (it is inside the hull, since it was accepted by add_point), so split that
       facet into three. Measured 5 such points per chunk before, none after. */
    {
        static unsigned char used[MAX_PTS + 3];
        memset(used, 0, (size_t)npts);
        for (int k = 0; k < ndt; k++) {
            if (!dt[k].alive) continue;
            used[dt[k].v[0]] = used[dt[k].v[1]] = used[dt[k].v[2]] = 1;
        }
        for (int p = 0; p < npts; p++) {
            if (used[p]) continue;
            float px2 = pts_x[p], pz2 = pts_z[p];
            /* 1. strictly inside a facet: split it into three. Absolute tolerance
               because the cross products scale with the facet, and a split that
               lands within a unit of an edge makes a triangle under a pixel wide
               -- a "repair" that leaves the needle standing. */
            int hit = -1;
            for (int k = 0; k < ndt && hit < 0; k++) {
                if (!dt[k].alive) continue;
                int va = dt[k].v[0], vb = dt[k].v[1], vc = dt[k].v[2];
                float ax = pts_x[va], az = pts_z[va];
                float bx = pts_x[vb], bz = pts_z[vb];
                float cx2 = pts_x[vc], cz2 = pts_z[vc];
                float d1 = (bx-ax)*(pz2-az) - (bz-az)*(px2-ax);
                float d2 = (cx2-bx)*(pz2-bz) - (cz2-bz)*(px2-bx);
                float d3 = (ax-cx2)*(pz2-cz2) - (az-cz2)*(px2-cx2);
                int pos = (d1 > 3.0f) + (d2 > 3.0f) + (d3 > 3.0f);
                int neg = (d1 < -3.0f) + (d2 < -3.0f) + (d3 < -3.0f);
                if (pos != 3 && neg != 3) continue;
                dt[k].alive = 0;
                dt_add(va, vb, p);
                dt_add(vb, vc, p);
                dt_add(vc, va, p);
                hit = k;
            }
            if (hit >= 0) { used[p] = 1; continue; }

            /* 2. sitting *on* an edge: splitting one facet into three makes one
               of them degenerate, dt_add drops it, and the long edge -- with the
               needle hanging off it -- survives. That is the border-ring needle:
               the sample is on the ring, the fill bridged the ring, and the
               player sees a triangle one unit wide and a hundred and sixty long.
               Both facets sharing the edge are split, into two each. */
            int ea = -1, eb = -1;
            for (int k = 0; k < ndt && ea < 0; k++) {
                if (!dt[k].alive) continue;
                for (int e = 0; e < 3; e++) {
                    int va = dt[k].v[e], vb = dt[k].v[(e + 1) % 3];
                    float dx = pts_x[vb] - pts_x[va], dz = pts_z[vb] - pts_z[va];
                    float l2 = dx*dx + dz*dz;
                    if (l2 < 1e-6f) continue;
                    float t = ((px2 - pts_x[va]) * dx + (pz2 - pts_z[va]) * dz) / l2;
                    if (t < 0.02f || t > 0.98f) continue;      /* not between */
                    float offx = pts_x[va] + dx * t - px2;
                    float offz = pts_z[va] + dz * t - pz2;
                    if (offx*offx + offz*offz > 1.0f) continue;   /* over a unit off */
                    ea = va; eb = vb;
                    break;
                }
            }
            if (ea < 0) continue;                              /* genuinely outside */
            for (int k = 0; k < ndt; k++) {
                if (!dt[k].alive) continue;
                int va = dt[k].v[0], vb = dt[k].v[1], vc = dt[k].v[2];
                if (!(va == ea || vb == ea || vc == ea)) continue;
                if (!(va == eb || vb == eb || vc == eb)) continue;
                int far2 = (va == ea || va == eb) ? ((vb == ea || vb == eb) ? vc : vb) : va;
                dt[k].alive = 0;
                dt_add(ea, p, far2);
                dt_add(p, eb, far2);
            }
            used[p] = 1;
        }
    }

    int ntri = 0, relit = 0, nowater_n = 0;
    for (int k = 0; k < ndt; k++) {
        if (!dt[k].alive) continue;
        float ax = pts_x[dt[k].v[0]], az = pts_z[dt[k].v[0]];
        float bx = pts_x[dt[k].v[1]], bz = pts_z[dt[k].v[1]];
        float qx = pts_x[dt[k].v[2]], qz = pts_z[dt[k].v[2]];
        float ha = sample_height(ax, az);
        float hb = sample_height(bx, bz);
        float hq = sample_height(qx, qz);
        float u[3] = { bx-ax, hb-ha, bz-az };
        float w[3] = { qx-ax, hq-ha, qz-az };
        /* How far this facet's own plane is from the ground under its middle,
           in units of the tier's spacing (1.0 = a third of a spacing). The
           counter reads this; it is computed here because the three corner
           heights are already in hand, so it costs one extra sample per facet
           rather than four. */
        {
            const float etol = 0.35f * (float)step * CELL;
            float dev = sample_height((ax + bx + qx) / 3.0f, (az + bz + qz) / 3.0f)
                      - (ha + hb + hq) / 3.0f;
            tri_gerr[k] = (dev < 0.0f ? -dev : dev) / etol;
        }
        nx_[k] = u[1]*w[2]-u[2]*w[1];
        ny_[k] = u[2]*w[0]-u[0]*w[2];
        nz_[k] = u[0]*w[1]-u[1]*w[0];
        float nl = sqrtf(nx_[k]*nx_[k]+ny_[k]*ny_[k]+nz_[k]*nz_[k]);
        /* A sliver is under a pixel wide, and its normal comes from three nearly
           collinear points: the direction is noise, and a noise normal shades
           the hairline dark, which is the thin dark line that used to lie across
           meadows and along shores. Point it straight up instead. The facet is
           still drawn, so skipping it cannot leave a pinhole either. */
        float e0 = u[0]*u[0] + u[2]*u[2];
        float e1 = w[0]*w[0] + w[2]*w[2];
        float e2 = (w[0]-u[0])*(w[0]-u[0]) + (w[2]-u[2])*(w[2]-u[2]);
        float blen = sqrtf(e0 > e1 ? (e0 > e2 ? e0 : e2) : (e1 > e2 ? e1 : e2));
        int sliver = blen > 1e-6f && nl / blen < 1.0f;
        if (nl < 1e-9f || sliver) { nx_[k]=0; ny_[k]=1; nz_[k]=0; }
        else { nx_[k]/=nl; ny_[k]/=nl; nz_[k]/=nl; }
        if (ny_[k] < 0.0f) { nx_[k]=-nx_[k]; ny_[k]=-ny_[k]; nz_[k]=-nz_[k]; }

        /* --- the chord is lit by the ground, not by its own plane ----------
           A facet whose plane deviates from the ground under its middle is not
           a surface: it is a chord over a crease (a pit, a river bank, a cliff
           edge). Lighting it by its own normal is what drew the dark shards --
           the plane tilted away from the sun while the ground it covers faces
           it. Past 60 degrees of deviation the normal comes from the heightfield
           instead, which is where the light actually lands. The geometry is
           untouched: round 2 measured that no inserted point repairs these (the
           fill re-creates them), and the honest fix is to shade the ground, not
           to pretend the chord is one. */
        {
            float mx = (ax + bx + qx) / 3.0f, mz = (az + bz + qz) / 3.0f;
            /* the estimate is taken at the tier's own spacing: at step 4 a facet
               spans 60 units, so a one-cell difference would measure the ground
               under a facet-width rather than the ground under the facet */
            const float hh = 0.5f * (float)step * (float)CELL;
            float gx = sample_height(mx + hh, mz) - sample_height(mx - hh, mz);
            float gz = sample_height(mx, mz + hh) - sample_height(mx, mz - hh);
            float g[3] = { -gx, 2.0f * hh, -gz };
            float gl = sqrtf(g[0]*g[0] + g[1]*g[1] + g[2]*g[2]);
            if (gl > 1e-9f) { g[0] /= gl; g[1] /= gl; g[2] /= gl; }
            float dot = nx_[k]*g[0] + ny_[k]*g[1] + nz_[k]*g[2];
            /* Slivers stay pointed up, deliberately: re-lighting them by the
               ground too was tried and put a dark line down a sunlit cliff,
               because a sliver sitting on a cliff *edge* takes the ground normal
               of the edge, which faces away from the sun. A hairline of the
               wrong brightness is the better fault. */
            if (!sliver && gl > 1e-9f && dot < 0.5f) {      /* more than 60 deg */
                nx_[k] = g[0]; ny_[k] = g[1]; nz_[k] = g[2];
                relit++;
            }
        }
        ntri++;
    }
    if (ntri < 8) return 0;

    /* --- PICK: which facet does the renderer draw at this pixel? ------------
       Prints every facet whose projection covers the pixel with the numbers
       needed to judge it: chunk, tier, distance, width, ground error, water
       class, colour and the three corners in world space and on screen. Facets
       hidden behind it print too, so the nearest is the answer.

       It projects with gfx_mvp -- the *same* matrix render() uploaded -- because
       the first version rebuilt the camera itself and answered with a facet 200
       units behind the viewer. PICK_PAINT=1 paints the hits, which is how this
       one was checked: the picked pixel came back magenta. */
    if (pick_x >= 0) {
        for (int k = 0; k < ndt; k++) {
            if (!dt[k].alive) continue;
            float sx[3], sy[3];
            int inside_screen = 1;
            for (int q = 0; q < 3; q++) {
                int p3 = dt[k].v[q];
                float nx, ny, nz;
                mat4_point(gfx_mvp, pts_x[p3], sample_height(pts_x[p3], pts_z[p3]),
                           pts_z[p3], &nx, &ny, &nz);
                sx[q] = (nx * 0.5f + 0.5f) * (float)gfx_w;
                sy[q] = (1.0f - (ny * 0.5f + 0.5f)) * (float)gfx_h;
                if (!(nz > 0.0f && nz < 1.0f)) inside_screen = 0;
            }
            if (!inside_screen) continue;               /* outside the frustum */
            float px = (float)pick_x, py = (float)pick_y;
            float d1 = (sy[1]-sy[2])*(sx[0]-sx[2]) + (sx[2]-sx[1])*(sy[0]-sy[2]);
            if (fabsf(d1) < 1e-9f) continue;
            float u = ((sy[1]-sy[2])*(px-sx[2]) + (sx[2]-sx[1])*(py-sy[2])) / d1;
            float v2 = ((sy[2]-sy[0])*(px-sx[2]) + (sx[0]-sx[2])*(py-sy[2])) / d1;
            if (u < 0.0f || v2 < 0.0f || u + v2 > 1.0f) continue;
            if (pick_paint) pick_hit[k] = 1;
            float h[3];
            for (int q = 0; q < 3; q++) {
                int p3 = dt[k].v[q];
                h[q] = sample_height(pts_x[p3], pts_z[p3]);
            }
            float ax = pts_x[dt[k].v[0]], az = pts_z[dt[k].v[0]];
            float ar = 0.5f * fabsf((pts_x[dt[k].v[1]] - ax) * (pts_z[dt[k].v[2]] - az)
                                  - (pts_z[dt[k].v[1]] - az) * (pts_x[dt[k].v[2]] - ax));
            float bl = 0.0f;
            for (int e = 0; e < 3; e++) {
                float dx = pts_x[dt[k].v[e]] - pts_x[dt[k].v[(e + 1) % 3]];
                float dz = pts_z[dt[k].v[e]] - pts_z[dt[k].v[(e + 1) % 3]];
                float l = sqrtf(dx*dx + dz*dz);
                if (l > bl) bl = l;
            }
            float cxm = (ax + pts_x[dt[k].v[1]] + pts_x[dt[k].v[2]]) / 3.0f;
            float czm = (az + pts_z[dt[k].v[1]] + pts_z[dt[k].v[2]]) / 3.0f;
            float cym = (h[0] + h[1] + h[2]) / 3.0f;
            float ddx = cxm - cam_x, ddy = cym - cam_y, ddz = czm - cam_z;
            fprintf(stderr, "PICKHIT ci=%d step=%d dist=%.1f width=%.2f gerr=%.2f wet=%d "
                    "col=%.2f,%.2f,%.2f ring=%d,%d,%d "
                    "a=(%.0f,%.0f,%.0f) b=(%.0f,%.0f,%.0f) c=(%.0f,%.0f,%.0f)\n",
                    ci, step, (double)sqrtf(ddx*ddx + ddy*ddy + ddz*ddz),
                    bl > 0.0f ? (double)(2.0f * ar / bl) : 0.0, (double)tri_gerr[k], tri_wet[k],
                    (double)tri_col[k][0], (double)tri_col[k][1], (double)tri_col[k][2],
                    pt_edge[dt[k].v[0]] ? 1 : 0, pt_edge[dt[k].v[1]] ? 1 : 0,
                    pt_edge[dt[k].v[2]] ? 1 : 0,
                    (double)pts_x[dt[k].v[0]], (double)pts_z[dt[k].v[0]], (double)h[0],
                    (double)pts_x[dt[k].v[1]], (double)pts_z[dt[k].v[1]], (double)h[1],
                    (double)pts_x[dt[k].v[2]], (double)pts_z[dt[k].v[2]], (double)h[2]);
        }
    }

    /* --- structural counts -------------------------------------------------
       The fill is a Delaunay of a jittered point set, so it can produce a facet
       nobody designed: the border ring is exactly collinear and the interior's
       spacing rule keeps its points a facet-width away from it, so the bridge
       is 100-150 units long. A long facet is the mechanism behind a colour
       taken 100 units from its corners and behind a water chord standing over
       a lake, so it is counted here instead of being hunted in a screenshot.
       Each is kept as the worst single chunk: a per-process total would depend
       on how many chunks happened to stream in, i.e. on the camera.
       The rim of the grid is excluded: a chunk at the world boundary has its
       ring clipped by the heightfield, so its fill is degenerate by
       construction, and it is the one place a player cannot stand. Those facets
       are real (see the world-edge item in PLAN.md) but they are not this
       measurement. */
    if (c0 > 0 && r0 > 0 && c1 < N - 1 && r1 < N - 1) {
        static unsigned char used[MAX_PTS + 3];
        memset(used, 0, (size_t)npts);
        int edge_long = 0, tri_tiny = 0, unused = 0, seam_gap = 0;
        float gerr = 0.0f;
        /* Relative to the fill's own spacing, not the cell: the interior rule
           already places points up to 36 units apart on flat ground, and a
           coarse tier places them a tier-interval apart. Past ~2.2x that, the
           edge is the triangulation bridging a gap it should have filled. */
        /* relative to the fill's own spacing, with room for the diagonal of a
           Delaunay cell and the jitter: 4.5x is a facet that is a gap, not a
           sample */
        const float elim = 4.5f * fmaxf(36.0f, (float)step * CELL);
        for (int k = 0; k < ndt; k++) {
            if (!dt[k].alive) continue;
            const int v[3] = { dt[k].v[0], dt[k].v[1], dt[k].v[2] };
            /* Area first: a run of near-collinear border points still yields a
               few triangles that span it. They are degenerate -- they draw
               nothing -- and their long "edges" are an artefact of the run, not
               a facet that needs splitting. */
            float ax0 = pts_x[v[0]], az0 = pts_z[v[0]];
            float tri_ar = 0.5f * fabsf((pts_x[v[1]] - ax0) * (pts_z[v[2]] - az0)
                                      - (pts_z[v[1]] - az0) * (pts_x[v[2]] - ax0));
            for (int e = 0; e < 3; e++) used[v[e]] = 1;

            float best = 0.0f, third = 0.0f;
            for (int e = 0; e < 3; e++) {
                int pa = v[e], pb = v[(e + 1) % 3];
                float dx = pts_x[pb] - pts_x[pa], dz = pts_z[pb] - pts_z[pa];
                float l = sqrtf(dx*dx + dz*dz);
                if (l > best) { third = best; best = l; }
                else if (l > third) third = l;
                /* A chain edge longer than one cell only exists at a coarse
                   tier, and it is shared with the neighbour's *finer* chain:
                   the deviation between this chord and the ground is the step
                   the neighbour draws one facet away. That is the seam. */
                if (l > 1.5f * CELL && (pt_edge[pa] & pt_edge[pb]) != 0) {
                    float dev = sample_height((pts_x[pa] + pts_x[pb]) * 0.5f,
                                              (pts_z[pa] + pts_z[pb]) * 0.5f)
                              - 0.5f * (sample_height(pts_x[pa], pts_z[pa])
                                      + sample_height(pts_x[pb], pts_z[pb]));
                    if (dev < 0.0f) dev = -dev;
                    if (dev > 1.0f) seam_gap++;
                }
            }
            /* Width, not area: a 200-by-1 sliver along a border run has 100
               units of area and is still not a surface. Below a unit it draws
               less than a pixel and has no business being called a facet. */
            float width = best > 0.0f ? 2.0f * tri_ar / best : 0.0f;
            if (width < 1.0f) tri_tiny++;          /* degenerate or sliver */
            else if (best > elim) edge_long++;
            if (width < 1.0f) continue;            /* not a surface: see above */
            if (tri_gerr[k] > gerr) gerr = tri_gerr[k];
        }
        for (int p = 0; p < npts; p++) if (!used[p]) unused++;
        if (edge_long > c_edge_long) c_edge_long = edge_long;
        if (tri_tiny  > c_tri_tiny)  c_tri_tiny  = tri_tiny;
        if (unused    > c_unused_pts) c_unused_pts = unused;
        if (seam_gap  > c_seam_gap)  c_seam_gap  = seam_gap;
        /* Two numbers, because they mean different things: at step 1 the facet
           is a surface the player stands on and a chord over a crease is a bug;
           at step 4 it is a coarse copy of a cliff, where any three points span
           the step and no insertion fixes it (measured: the worst facets are all
           tier 4, spanning 180-340 units of height). Gating the coarse one would
           gate the LOD's existence. */
        if (step <= 1 && gerr > c_ground_err) c_ground_err = gerr;
        if (gerr > c_ground_err_far) c_ground_err_far = gerr;
        /* Facets still lit by a normal that contradicts the ground: 0 by
           construction once the rule above applies, so this is the invariant
           that says the rule is actually reaching every facet. */
        /* How many facets needed re-lighting: the prevalence of the mechanism,
           not a defect count. The invariant "a facet is never lit by a normal
           that contradicts the ground under it" holds by construction now, so
           this is the alarm that says the mechanism is not spreading. */
        if (relit > c_relit) c_relit = relit;
        if (nowater_n > c_no_water) c_no_water = nowater_n;
    }

    /* One river query per vertex, not per facet: the water paint wants the
       minimum over a facet's three corners, and doing that inline cost four
       queries per triangle and made chunk builds slow enough to see. */
    for (int p = 0; p < npts; p++) {
        float lv = 0.0f, fxq = 0.0f, fzq = 0.0f, hwq = RIVER_HW_MIN;
        pt_riv[p] = river_query(pts_x[p], pts_z[p], &lv, &fxq, &fzq, &hwq) - hwq;
        pt_lvl[p] = lv; pt_fx[p] = fxq; pt_fz[p] = fzq;
    }

    /* --- one colour per facet ------------------------------------------- */
    float top = -1e9f, bot = 1e9f;
    int wet_col_dry = 0;
    for (int k = 0; k < ndt; k++) {
        if (!dt[k].alive) continue;
        float cxw = (pts_x[dt[k].v[0]] + pts_x[dt[k].v[1]] + pts_x[dt[k].v[2]]) / 3.0f;
        float czw = (pts_z[dt[k].v[0]] + pts_z[dt[k].v[1]] + pts_z[dt[k].v[2]]) / 3.0f;
        float ch[3];
        for (int q = 0; q < 3; q++)
            ch[q] = sample_height(pts_x[dt[k].v[q]], pts_z[dt[k].v[q]]);
        float cyw = (ch[0] + ch[1] + ch[2]) / 3.0f;
        if (cyw > top) top = cyw;
        if (cyw < bot) bot = cyw;

        /* Dry corners decide the colour of a facet that pokes out of the water.
           A facet spanning the shore used to be painted with the cell under its
           centre, which can be the seabed while a corner stands on the beach --
           that is the navy plate lying on an island. Its dry corners are the
           part of it the player sees, so their mean is the colour it should
           carry. A facet that is wholly below the surface keeps the centre
           sample: it *is* seabed, and averaging in a dry corner would only make
           the water look dirty. The look is otherwise unchanged -- one colour
           per facet, flat-shaded, no seams between facets. */
        float r, g, b, cc[3];
        {
            int ndry = (ch[0] > 0.0f) + (ch[1] > 0.0f) + (ch[2] > 0.0f);
            if (ndry == 0 || ndry == 3) {
                /* wholly one side of the waterline: the centre is a fair sample
                   and the old path costs one lookup instead of three */
                ground_colour_at(cr, cg, cb, cxw, czw, cc);
                r = cc[0]; g = cc[1]; b = cc[2];
            } else {
                float dr = 0.0f, dg = 0.0f, db = 0.0f;
                for (int q = 0; q < 3; q++) {
                    if (ch[q] <= 0.0f) continue;
                    ground_colour_at(cr, cg, cb, pts_x[dt[k].v[q]], pts_z[dt[k].v[q]], cc);
                    dr += cc[0]; dg += cc[1]; db += cc[2];
                }
                r = dr / (float)ndry; g = dg / (float)ndry; b = db / (float)ndry;
            }
        }
        /* How many facets the centre sample would have painted with the seabed
           while they have dry ground: the population this rule protects, not a
           fault. */
        if (sample_height(cxw, czw) <= 0.0f) {
            float cmax = ch[0] > ch[1] ? ch[0] : ch[1];
            if (ch[2] > cmax) cmax = ch[2];
            if (cmax > 0.5f) wet_col_dry++;
        }

        float steep = 1.0f - ny_[k];
        if (steep > 1.0f) steep = 1.0f;
        float fw = 0.30f + steep * 1.30f;
        if (fw > 1.0f) fw = 1.0f;
        float off = nx_[k]*pts_x[dt[k].v[0]] + ny_[k]*sample_height(pts_x[dt[k].v[0]], pts_z[dt[k].v[0]])
                  + nz_[k]*pts_z[dt[k].v[0]];
        float j = 1.0f + (FACET_SHADES[(int)(facet_shade(nx_[k],ny_[k],nz_[k],off,cxw,czw) * 4.0f) & 3]
                          - 1.0f) * fw;
        r *= j; g *= j; b *= j;

        float fx2 = 0.0f, fz2 = 0.0f, rx = 0.0f, rz = 0.0f;
        float river_lvl = 0.0f;
        /* the lake wins where the two overlap: a river mouth is still water,
           and painting it as a river put its moving ripple band on top of the
           lake as a bright dashed stripe */
        /* A lake facet is one the lake's *plane* covers: within two cells of a
           lake cell. Whether the bed is above or below the level there is the
           terrain's business -- the bed occludes the plane, and where it crosses
           is the waterline. Which is why a shoreline is a real edge now and not
           a boundary between painted facets. */
        /* The *lowest* level touching the facet, corners and centre alike. Two
           lakes can meet at different fills, and a facet taking the higher one
           left the lower lake's surface a step below it -- the step's exposed
           face is the bed, drawn as a strip of sand lying across the water. */
        float lake_lvl = lake_level_at(cxw, czw);
        /* Any corner counts, not just the centre. A facet whose middle falls on
           the bank but whose body crosses the water must still get a plane --
           otherwise the bed shows through it as a strip of sand lying across the
           lake, which is exactly what a centroid test drew. */
        for (int q = 0; q < 3; q++) {
            float lv = lake_level_at(pts_x[dt[k].v[q]], pts_z[dt[k].v[q]]);
            if (lv > lake_lvl) lake_lvl = lv;
        }
        int is_lake = lake_lvl > 0.0f;
        /* Painted by the *whole* facet, not by its centre: a channel is barely
           one facet wide on a steep reach, so a centre-only test left the river
           as a scatter of teal confetti with gaps between the patches. The
           most-inside vertex decides, from the per-point river distance
           computed once above -- four queries per facet made the chunk build
           slow enough to be visible as streaming. */
        int qi = -1;
        float inside = 1e18f;
        for (int q = 0; q < 3; q++) {
            int p = dt[k].v[q];
            if (pt_riv[p] < inside) { inside = pt_riv[p]; qi = p; }
        }
        if (qi >= 0) { river_lvl = pt_lvl[qi]; rx = pt_fx[qi]; rz = pt_fz[qi]; }
        /* A facet standing on end is a cascade, not a river surface. Painting
           the body colour there drew a river down a cliff as a staircase of
           blue walls (one per facet) standing in the fjord below. Steep river
           facets get the foam colour instead: what you see is water *falling*,
           which is what is actually there. */
        /* the facet's *centre* has to be in the channel: one corner inside is
           enough for the surface over it (a channel is narrower than a facet),
           but foam on a bank facet is a white wedge lying on the sand */
        float ins_mean = (pt_riv[dt[k].v[0]] + pt_riv[dt[k].v[1]] + pt_riv[dt[k].v[2]]) / 3.0f;
        int falling = ny_[k] < 0.55f && ins_mean < 0.0f;
        /* Where the surface goes. The bed keeps its terrain colour underneath
           and is what shows as the beach wherever it rises out of the water, so
           this loop decides the surface's height and its ripple and the emit
           pass below draws it. */
        tri_wet[k] = 0;
        if (is_lake) {
            fx2 = 1.6f; fz2 = 1.2f;      /* length 2: still water, no ripple band */
            tri_wet[k] = 1;
            for (int q = 0; q < 3; q++) tri_lvl[k][q] = lake_lvl;
        } else if (!falling && inside < 0.0f && river_bed_ok(cxw, czw)) {
            fx2 = rx; fz2 = rz;
            tri_wet[k] = 1;
            /* The surface follows the river's own fall, not the channel's
               cross-section: a facet's corners take the water level where they
               are, so a reach on a gradient is a tilted plane instead of a
               staircase of shelves. */
            for (int q = 0; q < 3; q++) {
                int p = dt[k].v[q];
                tri_lvl[k][q] = (pt_riv[p] < 2.0f * CELL && pt_lvl[p] > 5.0f)
                              ? pt_lvl[p] : river_lvl;
            }
            /* A waterfall is a river whose surface drops between here and two
               cells downstream. There is no foam simulation and no spray
               geometry: white facets on a steep reach read as falling water and
               cost one extra query on the few cells that qualify. It matters
               beyond looks -- the sim wants to know where the chokepoints are,
               and a fall is the best one a river offers. */
            float dn_lvl = river_lvl;
            if (river_query(cxw + rx * 2.0f * CELL, czw + rz * 2.0f * CELL,
                            &dn_lvl, NULL, NULL, NULL) < 40.0f
                && river_lvl - dn_lvl > 14.0f) {
                tri_wet[k] = 2;
                fx2 *= 2.4f; fz2 *= 2.4f;      /* faster ripple: it is falling */
            }
        } else if (falling) {
            /* A fall gets a surface like any other water, but tilted: each corner
               takes the river's level where it is, so the drop between two
               corners is spanned by one plane instead of being painted facet by
               facet on the cliff, which drew it as a white zig-zag. The clip is
               skipped for these (a fall hangs off the bed, it does not lie on
               it). */
            tri_wet[k] = 2;
            for (int q = 0; q < 3; q++) {
                int p = dt[k].v[q];
                tri_lvl[k][q] = (pt_riv[p] < 3.0f * CELL && pt_lvl[p] > 5.0f)
                              ? pt_lvl[p] : river_lvl;
            }
        }

        tri_col[k][0] = r; tri_col[k][1] = g; tri_col[k][2] = b;
        tri_flow[k][0] = fx2; tri_flow[k][1] = fz2;
    }
    if (wet_col_dry > c_wet_col_dry) c_wet_col_dry = wet_col_dry;
    /* Bounds are written by the builder and read by the cull on the render
       thread, which may be drawing the previous build of this chunk at the same
       time: a relaxed atomic is the honest description of that -- the values are
       a bound, and one build stale is still a bound. */
    __atomic_store_n(&chunks[ci].cy_top, (int)top, __ATOMIC_RELAXED);
    __atomic_store_n(&chunks[ci].cy_bot, (int)bot, __ATOMIC_RELAXED);

    /* --- emit ------------------------------------------------------------
       Trees are placed globally (the camera and the diagnostics walk that one
       list) but snapped and emitted here, against this chunk's own triangles:
       the drawn surface is the chord between vertices and sags inside a big
       facet, so a tree placed from the heightfield alone floats. */
    vtarget = chunk_verts;
    vcap = MAX_CHUNK_VERTS * VERT_FLOATS;
    vcount = 0;
    for (int k = 0; k < ndt; k++) {
        if (!dt[k].alive) continue;
        if (vcount + 3 * VERT_FLOATS > MAX_CHUNK_VERTS * VERT_FLOATS) { mesh_overflow++; break; }
        const float *bcp = bnc_pt[dt[k].v[0]];
        float nrm[3] = { nx_[k], ny_[k], nz_[k] };
        const float *fcol = tri_col[k];   /* the facet's colour, unless V_CLASS paints it */
        if (pick_paint && pick_hit[k]) fcol = vis_magenta;   /* PICK: show the answer */
        if (vis_class) {
            if (vis_match(vis_class, k, step)) fcol = vis_magenta;
        }
        /* The waterline is one polygon, used by both surfaces.
           The facet is cut where the bed crosses the surface level; the side
           whose bed is below the plane is underwater. A facet that is *mostly*
           underwater may still have a corner far above the plane -- the mesh is
           a Delaunay of a jittered point set, so a 100-unit facet can chord from
           a ridge into a lake -- and that corner is an artefact of the facet's
           size, not a beach. Such a facet hands the whole thing to the water:
           the bed is drawn only on the underwater polygon, the plane covers all
           of it, and nothing pokes through. A mostly-dry facet keeps its bed and
           gets the water on the underwater polygon only, so the waterline is
           exactly where the bed crosses. Neither case moves a vertex, so no
           step is left at the shore. */
        float ix[5][2], iy[5];
        int nv = 0, wet = tri_wet[k], sub = 0;
        /* A wet facet that ends up emitting no water surface is a hole in the
           water: the player sees whatever is behind it (a far cliff, the sky).
           This is the counter that would have caught the empty `wet && sub`
           branch, and it is an invariant, not an alarm -- every branch below
           that can be taken for a wet facet must emit a plane. */
        int drew_water = 0;
        if (wet) {
            for (int e = 0; e < 3; e++) {
                int id = dt[k].v[e], jd = dt[k].v[(e + 1) % 3];
                float bx = pts_x[id], bz = pts_z[id];
                float jx = pts_x[jd], jz = pts_z[jd];
                float da = tri_lvl[k][e]           - sample_height(bx, bz);
                float db = tri_lvl[k][(e + 1) % 3] - sample_height(jx, jz);
                if (da >= 0.0f) {
                    ix[nv][0] = bx; ix[nv][1] = bz; iy[nv] = tri_lvl[k][e]; nv++;
                }
                if ((da >= 0.0f) != (db >= 0.0f)) {
                    float t = da / (da - db);
                    ix[nv][0] = bx + (jx - bx) * t;
                    ix[nv][1] = bz + (jz - bz) * t;
                    iy[nv] = tri_lvl[k][e] + (tri_lvl[k][(e + 1) % 3] - tri_lvl[k][e]) * t;
                    nv++;
                }
            }
            float mx = (pts_x[dt[k].v[0]] + pts_x[dt[k].v[1]] + pts_x[dt[k].v[2]]) / 3.0f;
            float mz = (pts_z[dt[k].v[0]] + pts_z[dt[k].v[1]] + pts_z[dt[k].v[2]]) / 3.0f;
            sub = (wet == 2) || (sample_height(mx, mz) < tri_lvl[k][0] - 0.02f);
        }
        if (wet == 2) {
            /* A fall is a sheet on the rock, not a plane at the water level.
               Emitted at the reach's level per corner, every facet hung at a
               different height and pointed in a different direction, so a
               cascade read as a jumble of white plates. Glued to the bed with
               the facet's own normal it is one continuous sheet -- the plates
               were never in the reach, they were the level field. */
            float fx[3][2], fy[3], wx[3][2], wy[3];
            /* Offset along the facet's own normal, not straight up: on a face
               steeper than 45 degrees a vertical offset puts the sheet *inside*
               the rock over half the facet, and the two surfaces then fight for
               the same pixels -- visible as a dotted line down the fall. */
            float sox = nrm[0] * 0.4f, soy = nrm[1] * 0.4f, soz = nrm[2] * 0.4f;
            for (int e = 0; e < 3; e++) {
                int id = dt[k].v[e];
                fx[e][0] = pts_x[id]; fx[e][1] = pts_z[id];
                fy[e] = sample_height(pts_x[id], pts_z[id]);
                wx[e][0] = fx[e][0] + sox; wx[e][1] = fx[e][1] + soz;
                wy[e] = fy[e] + soy;
            }
            emit_fan(3, fx, fy, nrm, fcol, 0.0f, 0.0f, bcp, 0.0f);
            emit_fan(3, wx, wy, nrm, vis_class ? fcol : FOAM_COL,
                     tri_flow[k][0], tri_flow[k][1], bcp, 2.0f);
            drew_water = 1;
        } else if (wet && sub) {
            /* Mostly underwater: the whole facet is water, so the plane covers
               all of it and the bed is drawn under it (a corner that pokes
               above the level still shows as beach). This branch was left EMPTY
               by the fall-as-a-sheet change, which moved this body into the new
               `wet == 2` case and thereby deleted the surface from every lake
               facet whose bed is below the level -- the lake became a hole you
               could see the far cliff through. It is the default case for lake
               water, so it must never be empty. */
            float bx[3][2], by[3], wx[3][2], wy[3];
            for (int e = 0; e < 3; e++) {
                int id = dt[k].v[e];
                bx[e][0] = wx[e][0] = pts_x[id];
                bx[e][1] = wx[e][1] = pts_z[id];
                by[e] = sample_height(pts_x[id], pts_z[id]);
                wy[e] = tri_lvl[k][e];
            }
            emit_fan(3, bx, by, nrm, fcol, 0.0f, 0.0f, bcp, 0.0f);
            {
                const float up[3] = { 0.0f, 1.0f, 0.0f };
                emit_fan(3, wx, wy, up, vis_class ? fcol : WATER_COL,
                         tri_flow[k][0], tri_flow[k][1], bcp, 1.0f);
            }
        } else {
            float bx[3][2], by[3];
            for (int e = 0; e < 3; e++) {
                int id = dt[k].v[e];
                bx[e][0] = pts_x[id]; bx[e][1] = pts_z[id];
                by[e] = sample_height(pts_x[id], pts_z[id]);
            }
            emit_fan(3, bx, by, nrm, fcol, 0.0f, 0.0f, bcp, 0.0f);
            if (wet) {
                const float up[3] = { 0.0f, 1.0f, 0.0f };
                emit_fan(nv, ix, iy, up, vis_class ? fcol : WATER_COL,
                         tri_flow[k][0], tri_flow[k][1], bcp,
                         wet == 2 ? 2.0f : 1.0f);
                drew_water = 1;
            }
        }
        if (wet && !drew_water) nowater_n++;
    }
    /* Skirts. The border ring follows the tier, so a chunk and its neighbour
       only share a vertex chain when their tiers match. Where they differ, the
       two surfaces meet at slightly different heights and the gap shows as a
       sliver of sky. Drop a wall from every boundary edge: 40 units is far
       more than the chord error of the coarsest facet. Only tier 2+ chunks
       pay for it, because a fine chunk borders either fine chunks (exact
       match) or a coarse one, and the coarse side's wall closes the gap. */
    if (step > 1) {
        const float SK = 40.0f;
        for (int k = 0; k < ndt; k++) {
            if (!dt[k].alive) continue;
            if (vcount + 12 * VERT_FLOATS > MAX_CHUNK_VERTS * VERT_FLOATS) { mesh_overflow++; break; }
            const float *bcp = bnc_pt[dt[k].v[0]];
            float nrm[3] = { nx_[k], ny_[k], nz_[k] };
            for (int e = 0; e < 3; e++) {
                int a = dt[k].v[e], b = dt[k].v[(e + 1) % 3];
                if (!(pt_edge[a] & pt_edge[b])) continue;
                float pa[3] = { pts_x[a], sample_height(pts_x[a], pts_z[a]), pts_z[a] };
                float pb[3] = { pts_x[b], sample_height(pts_x[b], pts_z[b]), pts_z[b] };
                /* A wet facet's wall hangs from the *water surface* and is made
                   of water: hung from the bed it was a terrain wall poking up
                   through the lake wherever a tier boundary crossed it. */
                const float *wc = tri_col[k];
                float fa = 0.0f, fb = 0.0f;
                if (tri_wet[k]) {
                    pa[1] = tri_lvl[k][e];
                    pb[1] = tri_lvl[k][(e + 1) % 3];
                    wc = tri_wet[k] == 2 ? FOAM_COL : WATER_COL;
                    nrm[0] = 0.0f; nrm[1] = 1.0f; nrm[2] = 0.0f;
                    fa = tri_flow[k][0]; fb = tri_flow[k][1];
                }
                float wk = tri_wet[k] ? (tri_wet[k] == 2 ? 2.0f : 1.0f) : 0.0f;
                float wa = tri_wet[k] ? -2.0f : 0.0f;
                float da[3] = { pa[0], pa[1] - SK, pa[2] };
                float db[3] = { pb[0], pb[1] - SK, pb[2] };
                push_vert(pa, nrm, wc, wa,wk, fa, fb, bcp);
                push_vert(pb, nrm, wc, wa,wk, fa, fb, bcp);
                push_vert(db, nrm, wc, wa,wk, 0,0, bcp);
                /* both windings: the wall is visible from either side of it */
                push_vert(pa, nrm, wc, 0,0, 0,0, bcp);
                push_vert(db, nrm, wc, 0,0, 0,0, bcp);
                push_vert(da, nrm, wc, 0,0, 0,0, bcp);
            }
        }
    }

    int ntrees = 0;
    for (int t = 0; t < tree_count; t++) {
        if (chunk_of(trees[t].x, trees[t].z) != ci) continue;
        if (vcount + TREE_VERTS * VERT_FLOATS > MAX_CHUNK_VERTS * VERT_FLOATS) { mesh_overflow++; break; }
        float bx = trees[t].x, bz = trees[t].z;
        for (int k = 0; k < ndt; k++) {
            if (!dt[k].alive) continue;
            int id[3] = { dt[k].v[0], dt[k].v[1], dt[k].v[2] };
            float ax = pts_x[id[0]], az = pts_z[id[0]];
            float v0x = pts_x[id[1]] - ax, v0z = pts_z[id[1]] - az;
            float v1x = pts_x[id[2]] - ax, v1z = pts_z[id[2]] - az;
            float v2x = bx - ax, v2z = bz - az;
            float den = v0x*v1z - v1x*v0z;
            if (fabsf(den) < 1e-9f) continue;
            float u = (v2x*v1z - v1x*v2z) / den;
            float v = (v0x*v2z - v2x*v0z) / den;
            if (u < -0.02f || v < -0.02f || u + v > 1.02f) continue;
            trees[t].y = sample_height(ax, az) * (1.0f - u - v)
                       + sample_height(pts_x[id[1]], pts_z[id[1]]) * u
                       + sample_height(pts_x[id[2]], pts_z[id[2]]) * v;
            /* the tree takes the shade and the bounced light of the ground it
               stands in */
            sway_bounce = bnc_pt[id[0]];
            break;
        }
        emit_tree(&trees[t]);
        ntrees++;
    }
    if (nbld) emit_settlement(ci, step);
    (void)ntrees; (void)bot;

    mesh_pts += npts;
    mesh_tris += ntri;
    /* facets are no longer merged, so a facet is a triangle; the diagnostic
       keeps reporting the triangle count it used to call facets */
    mesh_facets += ntri;
    /* Peak vertex use against the hard budget. mesh_overflow only fires at the
       moment a chunk is truncated, so a chunk at 99% is a landmine that no
       assert sees; the percentage makes the approach visible. */
    {
        int pct = (int)(100.0 * (double)vcount / (double)(MAX_CHUNK_VERTS * VERT_FLOATS));
        if (pct > c_chunk_verts) c_chunk_verts = pct;
    }
    return vcount;
}

/* --- streaming -------------------------------------------------------------
   One worker thread, a job queue, and a chunk lifecycle the main thread owns.
   A chunk is built at a tier (interior spacing in cells) chosen from its
   distance to the camera, evicted when it is past the fog, and rebuilt when
   its tier changes -- which is what a frozen build could not do: fly into a
   chunk that was far away at startup and it stayed coarse.

   Chunk indices never change, so a rebuild is "destroy the buffer, queue the
   job at the new tier". Everything the worker reads is global and immutable
   after startup (heightfield, bakes, tree list), so build order cannot affect
   the result and --shot stays deterministic. */


/* tier -> world units between interior points. The band edges are what
   chunk_tier() and the hysteresis in chunks_update() agree on.
   Relative to the world like the fog is, because the point of a tier is to
   keep the facet the same size ON SCREEN: a 500-unit band on a 2200-unit
   island covers a quarter of it, on a 4400-unit one only an eighth, so the
   whole far half of a bigger world would be rendered at step 4 and read flat
   the moment the world grew. 500/2200 and 1000/2200 are the ratios. */

int chunk_tier(float d) {
    if (lod_clamp) return lod_clamp;   /* the overlay's LOD switch */
    if (getenv("NOLOD")) return 1;   /* A/B knob: dense everywhere */
    if (d < TIER_1_MAX) return 1;
    if (d < TIER_2_MAX) return 2;
    return 4;
}

int jobs_pending(void) {
    pthread_mutex_lock(&job_mu);
    int n = job_tail - job_head;
    if (jobs_in_flight > 0) n += jobs_in_flight;
    pthread_mutex_unlock(&job_mu);
    return n;
}

void job_push(int ci, int tier) {
    pthread_mutex_lock(&job_mu);
    if (job_tail - job_head < JOB_MAX) {
        job_q[job_tail % JOB_MAX] = ci | (tier << 12);
        job_tail++;
        pthread_cond_signal(&job_cv);
    }
    pthread_mutex_unlock(&job_mu);
}

/* --- environment bakes -----------------------------------------------------
   Ambient occlusion, the horizon sectors, the surface colours and the bounce
   are pure functions of the heightfield, the tree list and the seed, and their
   only consumer is the chunk builder. They ran on the main thread, which is
   why startup cost 56 ms at a 2200-unit world: an O(n^2) shadow march over 22k
   grid cells plus two full colour passes. On the worker they overlap with the
   chunk build, and the first frame arrives while they are still running. */


void bake_ambient(void) {
    for (int zi = 0; zi < N; zi++) {
        for (int xi = 0; xi < N; xi++) {
            float x = (xi / (float)(N - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            float z = (zi / (float)(N - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            sky_ao[zi * N + xi] = sky_occlusion(x, heights[zi * N + xi], z);
        }
    }
}

/* Colours per grid point (terrain-type only, lighting is in the shader). */
/* Ground colour for one point. Shared by the vertex bake and the map tool, so
   a world judged from above is coloured by the same rules as the world the
   player walks through -- reviewing terrain through a palette the game never
   shows is how a map view stops being evidence. */
/* Which kind of ground this is. The sim asks this (fertility, timber, harbours)
   and the colours come from the answer, so "the good farmland" the bots see is
   the green the player sees. */
static float ss01(float a, float b, float x) {
    if (x <= a) return 0.0f;
    if (x >= b) return 1.0f;
    float t = (x - a) / (b - a);
    return t * t * (3.0f - 2.0f * t);
}

/* Moisture: the one number that decides steppe vs meadow vs forest. Kept in
   its own function because the colour bake *blends* between the three while the
   sim *classifies* -- and both have to agree on how wet a place is.

   Three terms, all geography rather than decoration:
   - distance from the coast (interior is drier)
   - rain shadow, from marching upwind (west) and looking for a ridge
   - aspect: a north-facing slope (ground rising toward the south) is colder and
     holds its water, a south-facing one dries out
   plus a little noise so no band is a clean line. */
float biome_moisture(float x, float z, float h, float lat) {
    unsigned seed = terrain_seed;
    float cont = terrain_continent(x, z, seed);
    float interior = (cont - world_sea) / 0.40f;
    if (interior < 0.0f) interior = 0.0f;
    if (interior > 1.0f) interior = 1.0f;

    /* the wind comes from the west, so walk into it: a ridge 900 units upwind
       shadows just as much as one 200 units upwind, and a single probe only
       ever saw the nearest slope */
    float lee = 0.0f;
    float da[3] = { 250.0f, 600.0f, 1000.0f };
    for (int k = 0; k < 3; k++) {
        float up = surface_height(x - da[k], z);
        float sh = (up - h - 90.0f) / 520.0f;
        if (sh > lee) lee = sh;                 /* the tallest thing in the way */
    }
    if (lee < 0.0f) lee = 0.0f;
    if (lee > 1.0f) lee = 1.0f;

    /* aspect, as the downslope direction */
    float gx = surface_height(x + CELL, z) - surface_height(x - CELL, z);
    float gz = surface_height(x, z + CELL) - surface_height(x, z - CELL);
    float gm = sqrtf(gx * gx + gz * gz);
    float north = gm > 1e-3f ? (gz / gm) * 0.5f + 0.5f : 0.5f;   /* 1 = faces north */

    return 1.05f - 0.55f * interior - 0.75f * lee
         + 0.18f * (north - 0.5f)
         + 0.45f * (terrain_value_noise(x * 0.012f, z * 0.012f, seed + 41u) - 0.5f)
         + 0.10f * (1.0f - fabsf(lat - 0.5f) * 2.0f);
}

/* Exposure: how open a coastal cell is to the weather that comes off the sea.
   The wind is from the west, so a west-facing shore takes the swell and a
   sheltered one can hold sand. Returns 0 for open coast, 1 for shelter. */
float biome_shelter(float x, float z) {
    /* sample the sea out to the west: coast is sheltered when something stands
       between it and the open water */
    float blocked = 0.0f;
    float dist[3] = { 300.0f, 700.0f, 1200.0f };
    for (int k = 0; k < 3; k++) {
        float hs = surface_height(x - dist[k], z);
        if (hs < 0.0f) continue;                /* open sea: no shelter */
        blocked += 0.33f;
    }
    return blocked > 1.0f ? 1.0f : blocked;
}

int biome_id(float x, float z, float h, float slope, float lat) {
    unsigned seed = terrain_seed;
    if (h < 0.0f) return BIOME_SEA;
    if (h < 3.0f) {
        /* sand only where the sea can lay it down: a west-facing shore is
           under the swell and stays rock, a sheltered bay fills with sand */
        return biome_shelter(x, z) > 0.45f ? BIOME_SAND : BIOME_ROCK;
    }
    if (h > snow_line_at(lat)) return BIOME_SNOW;
    if (slope > 0.34f || terrain_mountain_mask(x, z, seed) > 0.78f) return BIOME_ROCK;

    float moist = biome_moisture(x, z, h, lat);
    if (moist < 0.26f) return BIOME_STEPPE;
    if (moist > 0.66f) return BIOME_FOREST;
    if (terrain_value_noise(x * 0.075f, z * 0.075f, seed + 9u) > 0.55f) return BIOME_DIRT;
    return BIOME_GRASS;
}

float snow_line_at(float lat) {
    float cold = 1.0f - fabsf(lat - 0.5f) * 2.0f;   /* 1 at the middle row */
    return 0.72f * peak_y * (0.80f + 0.35f * cold);
}

/* Ground colour for one point. Shared by the vertex bake and the map tool, so
   a world judged from above is coloured by the same rules as the world the
   player walks through -- reviewing terrain through a palette the game never
   shows is how a map view stops being evidence. */
void biome_rgb(float x, float z, float h, float slope, float lat, float *out) {
    float r, g, b;
    switch (biome_id(x, z, h, slope, lat)) {
    case BIOME_SEA:    r = 0.10f; g = 0.20f; b = 0.20f; break;
    case BIOME_SAND:   r = 0.63f; g = 0.57f; b = 0.41f; break;
    case BIOME_SNOW:   r = 0.90f; g = 0.86f; b = 0.79f; break;
    case BIOME_ROCK:   r = 0.46f; g = 0.31f; b = 0.17f; break;
    case BIOME_DIRT:   r = 0.27f; g = 0.18f; b = 0.08f; break;
    default: {
        /* Steppe, meadow and forest blend by moisture instead of switching at a
           threshold: hard bands read as a paint-by-numbers map from above and
           as a stripe from the ground. The classifications above still decide
           what the *sim* calls this place; only the colour is continuous. */
        unsigned seed = terrain_seed;
        float m = biome_moisture(x, z, h, lat);
        float ws = 1.0f - ss01(0.18f, 0.34f, m);       /* steppe weight */
        float wf = ss01(0.58f, 0.76f, m);              /* forest weight */
        float wg = 1.0f - ws - wf;
        if (wg < 0.0f) wg = 0.0f;
        float patch = 0.5f + 0.5f * terrain_value_noise(x * 0.022f, z * 0.022f, seed + 5u);
        float gr = 0.30f + 0.05f * patch;
        float gg = 0.355f + 0.045f * patch;
        float gb = 0.14f + 0.04f * (1.0f - patch);
        r = ws * 0.52f + wg * gr + wf * 0.24f;
        g = ws * 0.46f + wg * gg + wf * 0.31f;
        b = ws * 0.30f + wg * gb + wf * 0.15f;
        float cold = 1.0f - fabsf(lat - 0.5f) * 2.0f;
        float warm = cold - 0.75f;
        r += 0.05f * warm;
        g -= 0.02f * warm;
        b -= 0.05f * warm;
        break;
    }
    }
    out[0] = r; out[1] = g; out[2] = b;
}

void bake_colours(unsigned seed) {
    (void)seed;
    for (int zi = 0; zi < N; zi++) {
        for (int xi = 0; xi < N; xi++) {
            int i = zi * N + xi;
            float h = heights[i];
            float x = (xi / (float)(N - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            float z = (zi / (float)(N - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            int xm = xi > 0 ? xi - 1 : xi, xp = xi < N - 1 ? xi + 1 : xi;
            int zm = zi > 0 ? zi - 1 : zi, zp = zi < N - 1 ? zi + 1 : zi;
            float dhdx = (heights[zi * N + xp] - heights[zi * N + xm]) / ((xp - xm) * CELL);
            float dhdz = (heights[zp * N + xi] - heights[zm * N + xi]) / ((zp - zm) * CELL);
            float ny = 1.0f / sqrtf(1.0f + dhdx * dhdx + dhdz * dhdz);
            float slope = 1.0f - ny;
            float lat = zi / (float)(N - 1);

            float rgb[3];
            biome_rgb(x, z, h, slope, lat, rgb);
            float r = rgb[0], g = rgb[1], b = rgb[2];
            if (trees_only) { r = 0.475f; g = 0.435f; b = 0.396f; }   /* ref ground */

            /* no directional shadow here any more: it is evaluated per pixel
               from the baked horizon, so it follows the sun round the day.
               AO stays baked -- ambient occlusion does not care where the sun
               is, which is exactly why it can be. */
            float ao = 1.0f - 0.26f * sky_ao[i];
            bake_r[i] = r * ao; bake_g[i] = g * ao; bake_b[i] = b * ao;
        }
    }
}

/* Runs on the builder thread, in this order: each bake feeds the next and the
   chunks need all of them. */
void bake_environment(unsigned seed) {
    bake_ambient();
    bake_colours(seed);
    gcr = bake_r; gcg = bake_g; gcb = bake_b;
}

void *builder_main(void *arg) {
    unsigned seed = (unsigned)(uintptr_t)arg;
    bake_environment(seed);
    for (;;) {
        pthread_mutex_lock(&job_mu);
        while (job_head == job_tail && !builder_quit)
            pthread_cond_wait(&job_cv, &job_mu);
        if (builder_quit && job_head == job_tail) {
            pthread_mutex_unlock(&job_mu);
            break;
        }
        int job = job_q[job_head % JOB_MAX];
        job_head++;
        jobs_in_flight++;
        pthread_mutex_unlock(&job_mu);

        int ci = job & 0xFFF, tier = job >> 12;
        int words = chunk_build(ci, tier, seed, gcr, gcg, gcb);
        float *copy = words ? (float *)malloc((size_t)words * sizeof(float)) : NULL;
        if (copy) memcpy(copy, chunk_verts, (size_t)words * sizeof(float));

        pthread_mutex_lock(&job_mu);
        chunks[ci].data = copy;
        __atomic_store_n(&chunks[ci].words, copy ? words : 0, __ATOMIC_RELAXED);
        chunk_set_state(&chunks[ci], CHUNK_DONE);   /* publishes data/words */
        jobs_in_flight--;
        pthread_mutex_unlock(&job_mu);
    }
    pthread_mutex_lock(&job_mu);
    builder_live = 0;
    build_async_ms = stm_sec(stm_now() - builder_t0) * 1000.0;
    pthread_mutex_unlock(&job_mu);
    return NULL;
}

void start_streamer(unsigned seed) {
    for (int i = 0; i < NCHUNKS; i++) {
        chunk_set_state(&chunks[i], CHUNK_EMPTY);
        chunks[i].tier = 0;
        chunks[i].buf.id = SG_INVALID_ID;
        free(chunks[i].data);       /* built but never uploaded: a rebuild drops it */
        chunks[i].data = NULL;
        chunks[i].cx = i % CHUNK_GRID;
        chunks[i].cz = i / CHUNK_GRID;
    }
    job_head = job_tail = 0;
    jobs_in_flight = 0;
    builder_quit = 0;
    mesh_pts = mesh_tris = mesh_facets = 0;
    mesh_overflow = 0; tri_overflow = 0; pt_overflow = 0;
    c_edge_long = c_tri_tiny = c_unused_pts = c_wet_col_dry = c_seam_gap = 0;
    c_ground_err = c_ground_err_far = 0.0f; c_chunk_verts = 0;
    builder_t0 = stm_now();
    builder_live = 1;
    builder_started = 1;
    pthread_create(&builder, NULL, builder_main, (void *)(uintptr_t)seed);
}

void stop_streamer(void) {
    if (!builder_started) return;
    pthread_mutex_lock(&job_mu);
    builder_quit = 1;
    pthread_cond_signal(&job_cv);
    pthread_mutex_unlock(&job_mu);
    pthread_join(builder, NULL);
    builder_started = 0;
}



int nchunks_ready(void) {
    int n = 0;
    for (int i = 0; i < NCHUNKS; i++) if (chunk_state(&chunks[i]) == CHUNK_READY) n++;
    return n;
}

/* Everything queued has to be at its tier before a capture, or --shot could
   photograph a half-streamed world. */
/* Test hook: rebuild every chunk at its current tier. A rebuild must be
   invisible -- the old mesh keeps drawing until the new one is uploaded, and the
   loading overlay must not come back -- so this is how that is measured. */
void force_rebuild_all(void) {
    for (int i = 0; i < NCHUNKS; i++) {
        if (chunk_state(&chunks[i]) != CHUNK_READY || chunks[i].tier == 0) continue;
        chunk_set_state(&chunks[i], CHUNK_BUILDING);
        job_push(i, chunks[i].tier);
    }
}

int world_ready(void) {
    if (jobs_pending()) return 0;
    for (int i = 0; i < NCHUNKS; i++)
        if (chunk_state(&chunks[i]) == CHUNK_BUILDING || chunk_state(&chunks[i]) == CHUNK_DONE) return 0;
    return 1;
}

/* Decide what each chunk should be, once a frame, from the camera. Runs on the
   main thread because releasing a buffer is a sokol call. */
void chunks_update(void) {
    const float keep = FOG_FAR + CHUNK_WORLD * 0.75f;   /* evict beyond the haze */
    /* Speed-scaled hysteresis: a walking camera crosses a band edge for a
       couple of frames and would rebuild the same chunk twice; a running one
       crosses several. The dead band therefore has to grow with motion, or
       running along a boundary turns into continuous rebuilding -- which is
       visible, because a rebuild changes the mesh and the shading. */
    static float last_x = 0.0f, last_z = 0.0f;
    static int have_last = 0;
    float step_dist = have_last ? sqrtf((cam_x - last_x)*(cam_x - last_x)
                                      + (cam_z - last_z)*(cam_z - last_z)) : 0.0f;
    last_x = cam_x; last_z = cam_z; have_last = 1;
    /* 60 units at rest; ~4 units of band per unit of per-frame travel */
    float hyst = 60.0f + 4.0f * step_dist;
    if (hyst > 240.0f) hyst = 240.0f;
    for (int i = 0; i < NCHUNKS; i++) {
        float ccx = ((float)chunks[i].cx + 0.5f) * CHUNK_WORLD - TERRAIN_WORLD * 0.5f;
        float ccz = ((float)chunks[i].cz + 0.5f) * CHUNK_WORLD - TERRAIN_WORLD * 0.5f;
        float d = sqrtf((ccx - cam_x) * (ccx - cam_x) + (ccz - cam_z) * (ccz - cam_z));
        int want = (d < keep) ? chunk_tier(d) : 0;
        if (chunk_state(&chunks[i]) == CHUNK_BUILDING || chunk_state(&chunks[i]) == CHUNK_DONE) continue;
        if (chunk_state(&chunks[i]) == CHUNK_READY && chunks[i].tier == want) continue;
        if (chunk_state(&chunks[i]) == CHUNK_EMPTY && want == 0) continue;
        /* Hysteresis: a camera parked on a band edge must not rebuild the same
           chunk every frame. Inside the dead band the current tier stays. */
        if (chunk_state(&chunks[i]) == CHUNK_READY && want != 0 && want != chunks[i].tier) {
            float edge = (d < 0.5f * (TIER_1_MAX + TIER_2_MAX)) ? TIER_1_MAX : TIER_2_MAX;
            if (fabsf(d - edge) < hyst) continue;
        }
        if (want == 0) {
            /* evicted: nothing will replace it, so the buffer goes now */
            if (chunks[i].buf.id != SG_INVALID_ID) {
                sg_destroy_buffer(chunks[i].buf);
                chunks[i].buf.id = SG_INVALID_ID;
            }
            chunks[i].words = 0;
            chunk_set_state(&chunks[i], CHUNK_EMPTY);
            chunks[i].tier = 0;
            continue;
        }
        /* A tier change keeps the old buffer and keeps drawing it until the
           new mesh has been uploaded. Destroying it here punched a hole in the
           terrain for however many frames the rebuild took -- at walking speed
           that is a visible flash at every band the camera crosses. */
        stream_rebuilds++;
        chunks[i].tier = want;
        chunk_set_state(&chunks[i], CHUNK_BUILDING);
        job_push(i, want);
    }
}

/* sokol calls this for every validation failure; level 0 is a panic, after
   which it aborts. Printing the message is the entire point. */

/* Everything that is a pure function of the seed: the heightfield, the water,
   the trees. Split out because the map tool needs exactly this and nothing
   else -- no camera, no decor, no streamer. */
/* Pick the coastline threshold so the land fraction matches the archetype.
   A fixed threshold cannot: the continental field's distribution shifts per
   seed, which is how the same generator produced worlds from 25% to 51% land. */
static int cmp_float(const void *a, const void *b) {
    float x = *(const float *)a, y = *(const float *)b;
    return (x > y) - (x < y);
}

void pick_sea_level(unsigned seed) {
    enum { M = 96 };
    static float v[M * M];
    for (int i = 0; i < M * M; i++) {
        float x = ((i % M) / (float)(M - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
        float z = ((i / M) / (float)(M - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
        v[i] = terrain_continent(x, z, seed);
    }
    qsort(v, M * M, sizeof v[0], cmp_float);
    float target = terrain_gen(seed).land_target;
    int k = (int)((1.0f - target) * (float)(M * M - 1));
    world_sea = v[k];
}

int terrain_force = -1;   /* `--world NAME`: see terrain.h */

void build_world_data(unsigned seed) {
    pick_sea_level(seed);
    float peak_score = -1e9f;
    for (int zi = 0; zi < N; zi++) {
        for (int xi = 0; xi < N; xi++) {
            float x = (xi / (float)(N - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            float z = (zi / (float)(N - 1)) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            heights[zi * N + xi] = terrain_height(x, z, seed);
            /* The framing summit is scored, not just maximal: the tallest point
               in the world is often a spike on a small island, and a camera
               pointed at it frames one rock against open sea. Weighting by how
               far inland it is puts the camera on the big landmass instead. */
            float score = heights[zi * N + xi] + 260.0f * terrain_continent(x, z, seed);
            if (score > peak_score) {
                peak_score = score;
                peak_y = heights[zi * N + xi];
                peak_x = x;
                peak_z = z;
            }
        }
    }
    /* talus follows the cell: same slope limit as the old 1.35-unit cell, so
       the terrace risers survive erosion the same way they did */
    /* Talus scales with the archetype: a 1150-unit range needs a steeper angle
       than a 430-unit one, or erosion planes both into the same pancake. */
    worldgen_t gen = terrain_gen(seed);
    /* More passes than the terracing needs: thermal erosion is what turns a
       ridged-noise cone into a summit with shoulders, and a 1400-unit peak
       needs its flanks widened or it renders as a spike. */
    terrain_erode(heights, scratch, N, CELL, 6, gen.talus * CELL);
    /* Erosion relaxes, it does not enforce: a one-cell needle survives it. The
       clamp is generous (6 cells of drop per cell ~= an 80-degree wall), so it
       removes needles and leaves cliffs and range flanks alone. */
    terrain_despike(heights, N, 6.0f * CELL);
    {
        /* round the summits, but only the summits: thr sits above the ridge
           line so the meadows and the range flanks are untouched */
        float hi = 0.0f;
        for (int i = 0; i < N * N; i++) if (heights[i] > hi) hi = heights[i];
        terrain_smooth_highs(heights, scratch, N, 0.42f * hi, 4);
    }
    terrain_despike(heights, N, 6.0f * CELL);

    /* Lakes first: they flatten their basins, which changes where the river
       can run. Then carve the channel, before the shadow/AO bake so the water
       gets its own shading. */
    build_hydrology(seed);
    build_seg_index();
    carve_river();
    carve_river();
    carve_valleys();
    carve_river();
    close_lakes();
    settle_lakes();
    /* Again, and last: lake basins are flattened and the channel is carved
       after the first clamp, and both cut vertical steps into the field. */
    terrain_despike(heights, N, 6.0f * CELL);

    /* trees before anything that marches the horizon: a crown is an occluder */
    place_trees(seed);
    place_rocks(seed);
    build_tree_index();
    bake_horizon_grid();
    build_geography();
    place_settlement(seed);
    world_stats();
}

/* The numbers the world-gen invariants are written against: land fraction,
   how many landmasses are big enough to matter, and the relief the player can
   actually climb. Computed once after the field is final, so the sweep and the
   map tool report the same thing (they used to compute it separately). */
geo_cell_t geo[GEO_N * GEO_N];

/* ---------------------------------------------------------------- geography
   The sim's view of the terrain, at 275 units per cell: 64x64 cells for the
   whole world, one sample per place a settlement could plausibly care about.

   This is the honest version of "the sim depends on the coarse field, never the
   fine terrain" (PLAN rule 4). Before this, `sim.c` asked `sample_height()` and
   `river_query()` per candidate site, which works at 1184^2 and would be the
   first thing to break at 2368^2. Everything the sim scores a site by -- height,
   slope, moisture, biome, distance to water, distance to the sea, whether a
   pass runs through here -- is computed once, here, and then costs nothing. */
void build_geography(void) {
    for (int gz = 0; gz < GEO_N; gz++) {
        for (int gx = 0; gx < GEO_N; gx++) {
            float x = ((gx + 0.5f) / GEO_N) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            float z = ((gz + 0.5f) / GEO_N) * TERRAIN_WORLD - TERRAIN_WORLD * 0.5f;
            geo_cell_t *g = &geo[gz * GEO_N + gx];
            memset(g, 0, sizeof *g);
            g->h = surface_height(x, z);
            float dhx = (surface_height(x + CELL * 2, z) - surface_height(x - CELL * 2, z)) / (4.0f * CELL);
            float dhz = (surface_height(x, z + CELL * 2) - surface_height(x, z - CELL * 2)) / (4.0f * CELL);
            g->slope = sqrtf(dhx * dhx + dhz * dhz);
            float lat = (z + TERRAIN_WORLD * 0.5f) / TERRAIN_WORLD;
            g->moist = biome_moisture(x, z, g->h, lat);
            g->biome = biome_id(x, z, g->h, 1.0f - 1.0f / sqrtf(1.0f + g->slope * g->slope), lat);
            /* river distance from the coarse field the valley carver built */
            int cn = N / RIV_VC + 1;
            int cx = (int)((x + TERRAIN_WORLD * 0.5f) / CELL) / RIV_VC;
            int cz = (int)((z + TERRAIN_WORLD * 0.5f) / CELL) / RIV_VC;
            if (cx < 0) cx = 0; if (cx >= cn) cx = cn - 1;
            if (cz < 0) cz = 0; if (cz >= cn) cz = cn - 1;
            g->river_d = riv_dist[cz * cn + cx] * RIV_VC * CELL;
        }
    }

    /* distance to the sea, and passes: a pass is a saddle -- lower than the
       ground either side of it along one axis, higher along the other. That is
       the whole definition and it is enough for the sim to prefer a town that
       sits on a crossing. */
    static float sea_dist[GEO_N * GEO_N];
    static float sea_lvl[GEO_N * GEO_N];
    for (int i = 0; i < GEO_N * GEO_N; i++) {
        sea_dist[i] = geo[i].h < 0.0f ? 0.0f : 1e6f;
        sea_lvl[i] = 0.0f;
    }
    chamfer_2d(sea_dist, sea_lvl, GEO_N);
    for (int i = 0; i < GEO_N * GEO_N; i++)
        geo[i].sea_d = sea_dist[i] * (TERRAIN_WORLD / GEO_N);

    for (int gz = 1; gz + 1 < GEO_N; gz++) {
        for (int gx = 1; gx + 1 < GEO_N; gx++) {
            int i = gz * GEO_N + gx;
            float h = geo[i].h;
            float hl = geo[i - 1].h, hr = geo[i + 1].h;
            float hu = geo[i - GEO_N].h, hd = geo[i + GEO_N].h;
            /* a gap: the ground rises on both sides along one axis. It does
               not also have to be higher along the other -- a col is often the
               lowest way through and that is exactly why a road uses it */
            const float t = 30.0f;
            int we = (hl > h + t && hr > h + t);
            int ns = (hu > h + t && hd > h + t);
            /* a saddle is a pass only if it is high ground (in the hills, not
               on a hillock) and the shoulders either side actually stand above
               it -- without both tests a 64x64 grid of noise reports hundreds */
            float shoulder = we ? fminf(hl, hr) : fminf(hu, hd);
            float drop = fmaxf(shoulder - h, 0.0f);
            geo[i].pass = ((we || ns) && h > 0.28f * peak_y) ? 1 : 0;
            geo[i].pass_height = geo[i].pass ? drop : 0.0f;
        }
    }
}

/* How many passes this world has: a choke point count, and the number the map
   tool prints so a change in range shape shows up as a number. */
int pass_count(void) {
    int n = 0;
    for (int i = 0; i < GEO_N * GEO_N; i++) if (geo[i].pass) n++;
    return n;
}

int geo_at(float x, float z, geo_cell_t *out) {
    int gx = (int)(((x + TERRAIN_WORLD * 0.5f) / TERRAIN_WORLD) * GEO_N);
    int gz = (int)(((z + TERRAIN_WORLD * 0.5f) / TERRAIN_WORLD) * GEO_N);
    if (gx < 0) gx = 0; if (gx >= GEO_N) gx = GEO_N - 1;
    if (gz < 0) gz = 0; if (gz >= GEO_N) gz = GEO_N - 1;
    *out = geo[gz * GEO_N + gx];
    return 1;
}

void world_stats(void) {
    static unsigned char seen[N * N];
    static int stack[N * N];
    int land = 0;
    float lo = 1e9f, hi = -1e9f;
    for (int i = 0; i < N * N; i++) {
        seen[i] = 0;
        if (heights[i] < lo) lo = heights[i];
        if (heights[i] > hi) hi = heights[i];
        if (heights[i] > 0.0f) land++;
    }
    land_pct = 100.0f * (float)land / (float)(N * N);
    world_relief = hi - lo;

    /* A non-finite height is the one corruption that renders without saying
       anything: NaN compares false against everything, so it silently stops
       being land, casts no shadow, and the frame still looks like weather.
       Check the field once per world instead of every vertex; everything the
       mesh emits is derived from it. */
    world_nonfinite = 0;
    for (int i = 0; i < N * N; i++) if (!isfinite(heights[i])) world_nonfinite++;
    for (int t = 0; t < tree_count; t++)
        if (!isfinite(trees[t].x) || !isfinite(trees[t].y) || !isfinite(trees[t].z)
            || !isfinite(trees[t].r)) world_nonfinite++;
    for (int b = 0; b < nbld; b++)
        if (!isfinite(blds[b].x) || !isfinite(blds[b].z)) world_nonfinite++;
    if (world_nonfinite) fprintf(stderr, "world: %d non-finite samples (seed %u)\n",
                                 world_nonfinite, terrain_seed);

    /* A landmass is only worth calling a landmass if it can hold a town: a
       town needs low ground, a mild slope and to not be a lake. This is a
       cheap proxy for the sim's own scoring -- it can be wrong about *where*
       a town goes, but not about whether one can go here at all. */
    int masses = 0, town_masses = 0, viable_total = 0;
    for (int i = 0; i < N * N; i++) {
        if (heights[i] <= 0.0f || seen[i]) continue;
        int sp = 0, cells = 0, viable = 0;
        stack[sp++] = i; seen[i] = 1;
        while (sp) {
            int c = stack[--sp];
            cells++;
            int cx = c % N, cz = c / N;
            if ((cx & 3) == 0 && (cz & 3) == 0 && cx > 0 && cz > 0 && cx + 1 < N && cz + 1 < N) {
                float h = heights[c];
                float dhx = heights[c + 1] - heights[c - 1];
                float dhz = heights[c + N] - heights[c - N];
                float slope = 1.0f - 1.0f / sqrtf(1.0f + 0.25f * (dhx * dhx + dhz * dhz));
                if (h > 8.0f && h < 1200.0f && slope < 0.18f && !lake_cell[c]) viable++;
            }
            if (cx > 0     && !seen[c - 1] && heights[c - 1] > 0.0f) { seen[c - 1] = 1; stack[sp++] = c - 1; }
            if (cx + 1 < N && !seen[c + 1] && heights[c + 1] > 0.0f) { seen[c + 1] = 1; stack[sp++] = c + 1; }
            if (cz > 0     && !seen[c - N] && heights[c - N] > 0.0f) { seen[c - N] = 1; stack[sp++] = c - N; }
            if (cz + 1 < N && !seen[c + N] && heights[c + N] > 0.0f) { seen[c + N] = 1; stack[sp++] = c + N; }
        }
        if (cells > 400) {
            masses++;
            if (viable * 9 >= 32) town_masses++;   /* stride-4 sampled cells */
            viable_total += viable * 9;
        }
    }
    land_masses = masses;
    land_town_masses = town_masses;
    land_viable = viable_total;
}

void build_terrain(unsigned seed) {
    build_world_data(seed);
    /* the start vantage has to see past the trees it stands in */
    if (!have_view) { pick_camera(); clear_start_clearing(); }
    trees_selfcheck();

    /* Weather that does not belong to a chunk: the sea plane, clouds, birds.
       Emitted here because the clouds are placed in the camera's view cone and
       this is everything the first frame needs; the rest waits on the worker. */
    vtarget = verts;
    vcap = DECOR_VERTS * VERT_FLOATS;
    vcount = 0;
    emit_water();
    emit_cloud(seed);
    emit_birds(seed);
    decor_words = vcount;

    start_streamer(seed);
    if (headless) {
        int lit = 0, rn = 0;
        double relief = 0.0;
        lit = N * N - (shadowed_pct() * N * N) / 100;
        for (int zi = 0; zi < N; zi++)
            for (int xi = 0; xi + 1 < N; xi++) {
                relief += fabs(heights[zi*N+xi+1] - heights[zi*N+xi]);
                rn++;
            }
        /* no shadow figure here: the horizon bake now runs on the worker, so
           at this point nothing is shaded yet. The capture sidecar reports it
           once the world has settled. */
        (void)lit;
        int nrock = 0;
        for (int i = 0; i < tree_count; i++) if (trees[i].kind == TREE_ROCK) nrock++;
        fprintf(stderr, "terrain: trees=%d rocks=%d mean |dh| per cell=%.2f (cell %.2f) peak=%.0f,%.0f,%.0f\n",
                tree_count - nrock, nrock, relief / rn, CELL, peak_x, peak_y, peak_z);
    }
}

/* --- one place: placement, drawing, collision ----------------------------- */

void place_settlement(unsigned seed) {
    nbld = 0;
    if (settlement_site < 0) return;
    /* The town is a *record* made geometry: ask the sim where the place is and
       how big it is, then build it. The sim is initialised here because a shot
       does not otherwise need it. */
    sim_init(seed);
    float sx, sz, cap = 0.0f;
    const char *nm = "?";
    if (!sim_site_loc(settlement_site, &sx, &sz, &cap, &nm)) {
        fprintf(stderr, "settlement: this world has %d sites, %d was asked for\n",
                sim_site_count(), settlement_site);
        settlement_site = -1;
        return;
    }
    int want = 10 + (int)(cap / 22.0f);            /* 10 .. ~130 houses */
    if (want > MAX_BLD) want = MAX_BLD;
    int rows = 1;
    while ((rows + 1) * (rows + 1) <= want) rows++;
    int cols = (want + rows - 1) / rows;
    town_x = sx; town_z = sz;
    town_y = surface_height(sx, sz);
    town_r = (float)rows * ROW_PITCH * 0.5f + 18.0f;

    /* Rows, not a scatter: houses in a row nearly touch (a gap is an alley),
       rows are a street apart. A jittered grid of separate boxes reads as
       debris in a field, which is exactly what the first version looked like. */
    for (int j = 0; j < rows; j++) {
        unsigned rh = terrain_hash(j + 17, 5, seed ^ 0x2f1u);
        /* each row starts a little further along, or every house edge lines up
           into one long wall down the town */
        float cursor = sx - (float)cols * 9.0f + (float)(rh % 7u) * 1.6f - 5.0f;
        float bz = sz + ((float)j - (float)(rows - 1) * 0.5f) * ROW_PITCH
                 + (float)((rh >> 3) % 5u) - 2.0f;
        for (int i = 0; i < cols; i++) {
            unsigned h = terrain_hash(i + 71, j + 913, seed ^ 0x51ed2bu);
            float u1 = (float)((h >> 7) & 255u) / 255.0f;
            float u2 = (float)((h >> 15) & 255u) / 255.0f;
            float u3 = (float)((h >> 23) & 127u) / 127.0f;
            float w = 10.0f + 5.0f * u1, d = 9.0f + 4.0f * u2;
            float bx = cursor + w * 0.5f;
            cursor += w + 3.0f + 4.0f * u2 + ((h % 100u) < 10u ? 13.0f : 0.0f);
            if (bx > sx + 0.5f * (float)cols * 20.0f) break;
            /* Sit on the lowest corner, so a house is dug into the slope rather
               than floating off the downhill side. */
            float lo = 1e9f, hi = -1e9f;
            int drowned = 0;
            for (int k = 0; k < 5; k++) {
                float gx = bx + ((k & 1) ? w : -w) * 0.5f;
                float gz = bz + ((k & 2) ? d : -d) * 0.5f;
                if (k == 4) { gx = bx; gz = bz; }         /* centre too */
                float g = surface_height(gx, gz);
                if (g < lo) lo = g;
                if (g > hi) hi = g;
                /* The corners, not just the middle, and the water *level*, not
                   just the distance to the centre line: a house half in the
                   river or standing in the shallows of a lake is exactly the
                   defect this catches. */
                float rl = 0.0f, rfx = 0.0f, rfz = 0.0f, rhw = 0.0f;
                /* the water facets reach a facet diagonal past the half-width,
                   so the margin is generous; a house is 15 units wide and its
                   corner is what overlaps */
                if (river_query(gx, gz, &rl, &rfx, &rfz, &rhw) < rhw + 4.0f) drowned = 1;
                if (lake_at(gx, gz)) drowned = 1;
            }
            if (drowned) continue;
            if (lo < 3.0f) continue;                      /* in the sea */
            if (hi - lo > 6.0f) continue;                 /* a cliff is not a plot */
            if (nbld >= want) break;
            bld_t *b = &blds[nbld++];
            b->x = bx; b->z = bz; b->y = lo;
            b->w = w; b->d = d;
            b->h = 5.5f + 4.5f * u3;
            b->rh = 2.5f + 3.0f * u2;
            b->wall = (unsigned char)((h >> 5) % 3u);
            b->roof = (unsigned char)((h >> 11) % 3u);
            /* its shade comes from the horizon field the ground under it uses:
               sampled per fragment, so a house needs no stored horizon */
        }
    }

    /* The plot is cleared, not just the footprints: a town with forest growing
       in its streets reads as rubble in a field. Removing trees changes the
       bucket index, so it is rebuilt -- the horizon bake that already ran saw
       the old one, which only means a few tree shadows land where a house now
       stands. */
    for (int t = 0; t < tree_count; ) {
        if (fabsf(trees[t].x - town_x) < town_r + 4.0f &&
            fabsf(trees[t].z - town_z) < town_r * 0.72f + 4.0f) trees[t] = trees[--tree_count];
        else t++;
    }
    build_tree_index();

    /* one runnable check: a town with no houses, or a house off the ground, is
       the failure mode of the layout maths and is invisible as a number */
    assert(nbld > 0 && nbld <= MAX_BLD);
    for (int i = 0; i < nbld; i++)
        assert(blds[i].y > 3.0f && blds[i].w > 2.0f && blds[i].d > 2.0f);
    /* the one thing collision must do: a house is solid, the field outside the
       town is not */
    assert(settle_blocked(blds[0].x, blds[0].z));
    assert(!settle_blocked(town_x + town_r + 400.0f, town_z));

    fprintf(stderr, "settlement: %s, %d buildings, %.0f people, centre %.0f,%.0f, first %.0f,%.0f %.0fx%.0f\n",
            nm, nbld, cap, town_x, town_z, blds[0].x, blds[0].z, blds[0].w, blds[0].d);
}

/* A wall stops the walker. Axis-separated in sim_step, so hitting one corner
   of a house slides along it instead of sticking. */
int settle_blocked(float x, float z) {
    for (int i = 0; i < nbld; i++) {
        const bld_t *b = &blds[i];
        if (fabsf(x - b->x) < b->w * 0.5f + 0.6f &&
            fabsf(z - b->z) < b->d * 0.5f + 0.6f) return 1;
    }
    return 0;
}

static void emit_quad(const float *p0, const float *p1, const float *p2,
                      const float *p3, const float *inner, const float *col) {
    emit_tri(p0, p1, p2, inner, col, 1.0f);
    emit_tri(p0, p2, p3, inner, col, 1.0f);
}

static void emit_building(const bld_t *b) {
    static const float walls[3][3] = {
        { 0.80f, 0.76f, 0.67f },   /* lime plaster */
        { 0.68f, 0.63f, 0.55f },   /* stone */
        { 0.54f, 0.44f, 0.32f },   /* timber */
    };
    static const float roofs[3][3] = {
        { 0.56f, 0.42f, 0.22f },   /* thatch */
        { 0.42f, 0.44f, 0.49f },   /* slate */
        { 0.63f, 0.34f, 0.22f },   /* tile */
    };
    float x0 = b->x - b->w * 0.5f, x1 = b->x + b->w * 0.5f;
    float z0 = b->z - b->d * 0.5f, z1 = b->z + b->d * 0.5f;
    float yb = b->y - 2.5f;            /* buried, so a slope shows no gap */
    float yt = b->y + b->h;
    float ry = yt + b->rh;
    float inner[3] = { b->x, (yb + yt) * 0.5f, b->z };
    float ri[3] = { b->x, yt, b->z };
    const float *wc = walls[b->wall % 3], *rc = roofs[b->roof % 3];

    float p[4][3] = {
        { x0, yb, z0 }, { x1, yb, z0 }, { x1, yt, z0 }, { x0, yt, z0 } };
    emit_quad(p[0], p[1], p[2], p[3], inner, wc);          /* north wall */
    float q[4][3] = {
        { x0, yb, z1 }, { x1, yb, z1 }, { x1, yt, z1 }, { x0, yt, z1 } };
    emit_quad(q[0], q[1], q[2], q[3], inner, wc);          /* south wall */
    float s[4][3] = {
        { x0, yb, z0 }, { x0, yb, z1 }, { x0, yt, z1 }, { x0, yt, z0 } };
    emit_quad(s[0], s[1], s[2], s[3], inner, wc);          /* west wall */
    float e[4][3] = {
        { x1, yb, z0 }, { x1, yb, z1 }, { x1, yt, z1 }, { x1, yt, z0 } };
    emit_quad(e[0], e[1], e[2], e[3], inner, wc);          /* east wall */

    /* Gable roof, ridge along x, with a small overhang. Winding does not matter
       (the pipeline culls nothing); emit_tri aims the normal away from the
       inner point, which is what makes the two slopes differ in brightness. */
    float r0[3] = { x0 - 0.6f, ry, b->z }, r1[3] = { x1 + 0.6f, ry, b->z };
    float t0[3] = { x0 - 0.6f, yt, z0 - 0.6f }, t1[3] = { x1 + 0.6f, yt, z0 - 0.6f };
    float u0[3] = { x0 - 0.6f, yt, z1 + 0.6f }, u1[3] = { x1 + 0.6f, yt, z1 + 0.6f };
    emit_quad(t0, t1, r1, r0, ri, rc);
    emit_quad(u0, u1, r1, r0, ri, rc);
    emit_tri(p[3], q[3], r0, ri, rc, 1.0f);                /* gable ends */
    emit_tri(p[2], q[2], r1, ri, rc, 1.0f);
}

/* Only the finest tier draws houses: at tier 2 and 4 the ground mesh is coarser
   than the field the houses are snapped to, so they would float or sink. Tier 1
   reaches 4000 units out, and a town is a few pixels far beyond that. */
static void emit_settlement(int ci, int step) {
    if (step > 1) return;
    for (int i = 0; i < nbld; i++) {
        if (chunk_of(blds[i].x, blds[i].z) != ci) continue;
        if (vcount + 60 * VERT_FLOATS > MAX_CHUNK_VERTS * VERT_FLOATS) { mesh_overflow++; break; }
        /* Same rule as a tree: it takes the shade of the ground it stands on.
           No sway -- a house does not bend in the wind, so the sway height is
           pushed out of reach. */
        sway_bounce = NULL;
        sway_base = 1.0e6f;
        sway_h = 1.0f;
        emit_building(&blds[i]);
    }
}

/* Framing wants a low vantage across land with the peak high in frame. A fixed
   camera gives cliffs or open sea on half the seeds, so search azimuths x radii
   and score what the camera actually sees: is the summit unoccluded, does it
   subtend roughly the share of frame height the reference peak does, is the
   foreground flat enough to read as meadow.
   ponytail: coarse search, a few hundred height samples, runs once per launch. */
void pick_camera(void) {
    /* A town is the subject when there is one: stand back and above its
       southern corner, looking at the middle of the grid. */
    if (nbld) {
        /* stand off far enough that the town spans most of the frame, on land,
           from whichever side is highest (a vantage, not a wet rock) */
        float d = town_r * 1.8f + 30.0f;
        float eye = town_y + d * 0.34f + 8.0f;
        float best = -1e9f;
        cam_x = town_x; cam_z = town_z + d;
        for (int k = 0; k < 24; k++) {
            float a = (float)k * 6.28318531f / 24.0f;
            float x = town_x + cosf(a) * d, z = town_z + sinf(a) * d;
            float g = surface_height(x, z);
            if (g < 4.0f || lake_at(x, z)) continue;
            /* the sight line to the town must clear the ground, or the shot is
               a wall of rock with a town behind it */
            float worst = 0.0f;
            for (int s = 1; s < 12; s++) {
                float t = (float)s / 12.0f;
                float ray = eye + (town_y - eye) * t;
                float over = surface_height(x + (town_x - x) * t, z + (town_z - z) * t) - ray;
                if (over > worst) worst = over;
            }
            float score = -worst - fabsf(g - town_y) * 0.2f;
            if (score > best) { best = score; cam_x = x; cam_z = z; }
        }
        /* above the rooftops on a fixed 3/4 angle: the vantage's own height
           is only used to choose the side, not to aim */
        cam_y = eye;
        float dx = town_x - cam_x, dz = town_z - cam_z;
        yaw = tyaw = atan2f(dx, dz);
        pitch = tpitch = atan2f(town_y + 0.2f * town_r - cam_y, d);
        return;
    }
    const float fovy = 1.0f;          /* must match frame()'s perspective */
    const float want = 0.40f;         /* target summit elevation, radians */
    float start_az, start_elev;
    sun_angles(day_hours, &start_az, &start_elev);
    float best = 1e9f, bx = 0.0f, bz = 0.0f, bEye = 0.0f;
    /* Distance at which a summit peak_y above eye height sits at `want`.
       Capped: a tall peak would otherwise put the camera so far back that the
       frame is all foreground meadow, which is what a bigger island does. */
    /* The cap has to scale with the world. 620 was chosen for an 8800-unit map
       and, at 17600, parks the camera at the summit's foot with open sea behind
       it -- a portrait of one rock instead of a landscape. */
    const float want_d = fminf((peak_y - 8.0f) / tanf(want), 0.18f * TERRAIN_WORLD);
    for (int k = 0; k < 32; k++) {
        float a = (float)k * 6.28318531f / 32.0f;
        /* try every radius, not just the first land one: breaking at the first
           hit always keeps the farthest reachable vantage, which frames the
           summit small */
        for (int si = 0; si <= 10; si++) {
            float d = want_d * (1.0f - 0.06f * (float)si);
            float x = peak_x + cosf(a) * d, z = peak_z + sinf(a) * d;
            float h = surface_height(x, z);
            if (h < 4.0f) continue;
            /* a lake basin is flat ground at the water surface, so the height
               test passes and the camera stands in the water */
            if (lake_at(x, z)) continue;
            float eye = h + 7.0f;                          /* standing on it */
            float dx = peak_x - x, dz = peak_z - z;
            float dist = sqrtf(dx * dx + dz * dz);
            if (dist < 60.0f) continue;                    /* nose against it */
            float elev = atan2f(peak_y - eye, dist);
            /* occluders: terrain poking above the line of sight to the summit.
               Also the tallest thing anywhere in front, as an angle: a nearer
               crest the sight line clears sideways still fills the frame, and
               that is the failure this catches -- a wall of rock with the
               summit cut off above it. */
            int blocked = 0;
            float top_ang = 0.0f;
            for (int s = 1; s < 24; s++) {
                float t = (float)s / 24.0f;
                float ray = eye + (peak_y - eye) * t;
                float g = surface_height(x + dx * t, z + dz * t);
                if (g > ray) blocked++;
                float dd = dist * t;
                if (dd > 8.0f) {
                    float ag = atan2f(g - eye, dd);
                    if (ag > top_ang) top_ang = ag;
                }
            }
            /* and trees on that line: the heightfield test alone calls the
               summit visible when it is behind a wall of pines */
            float len2 = dx * dx + dz * dz;
            if (len2 > 1e-3f) {
                for (int ti = 0; ti < tree_count; ti++) {
                    const tree_t *tr = &trees[ti];
                    float t = ((tr->x - x) * dx + (tr->z - z) * dz) / len2;
                    if (t <= 0.02f || t >= 0.98f) continue;
                    float px = x + dx * t, pz = z + dz * t;
                    float ox = tr->x - px, oz = tr->z - pz;
                    if (ox * ox + oz * oz > tr->r * tr->r * 1.44f) continue;
                    float ray = eye + (peak_y - eye) * t;
                    if (tr->y < ray && tr->y + tr->h > ray) blocked++;
                }
            }
            /* flat ground reads as meadow, steep as cliff. Measured over ONE
               cell, not two: a facet is ~20 units across, so averaging over 58
               units calls a single steep slab flat and the camera ends up
               standing on it with rock filling half the frame. */
            float e = CELL;
            float sx = surface_height(x + e, z) - surface_height(x - e, z);
            float sz = surface_height(x, z + e) - surface_height(x, z - e);
            float slope = sqrtf(sx * sx + sz * sz) / (2.0f * e);
            /* A steep spot is penalised, not rejected: rejecting every steep
               candidate can leave the search with none at all, and the
               fallback is a fixed world position that means nothing on a
               generated island -- the camera ends up at the mountain's foot. */
            float cost = 0.0f;
            if (slope > 0.36f) cost += 40.0f;
            /* Stand in the valley, not on the mountain. A shoulder of the
               massif matches the target summit elevation exactly -- and then
               the mountain's own flank fills the bottom half of the frame. */
            if (terrain_mountain_mask(x, z, terrain_seed) > 0.15f) cost += 40.0f;
            cost += 4.0f * (float)blocked + 8.0f * fabsf(elev - want) + 3.0f * slope;
            /* the frame holds one summit, not a range wall: charge the search
               for anything in front that stands well above the target angle */
            if (top_ang > want * 1.2f) cost += 60.0f + 120.0f * (top_ang - want);
            /* ground immediately in front of the eye must fall away, or the
               camera stands in a hollow and a near bank fills the frame */
            for (int st = 1; st <= 6; st++) {
                float t = (float)st * 0.03f;
                if (surface_height(x + dx * t, z + dz * t) > eye - 2.0f) cost += 4.0f;
            }
            /* And the ground has to keep falling for the first ~50 units. On
               level meadow the eye sits 7 up, everything ahead is 7 down, the
               test above passes -- and the near ground is one plane filling
               the bottom third of the frame. A brow that drops away gives the
               foreground facets instead. */
            {
                float l = sqrtf(dx * dx + dz * dz);
                if (l > 1.0f) {
                    float ux = dx / l, uz = dz / l;
                    float ahead = surface_height(x + ux * 50.0f, z + uz * 50.0f);
                    if (ahead > eye - 5.0f) cost += 8.0f;
                }
            }
            /* do not stand the camera in the massif's shadow: with a low sun
               that is most of the valley, and the whole foreground renders as
               one dark slab */
            {
                float ch[SUN_SECTORS];
                horizon_at(x, z, h, 1, ch);
                if (shadow_lit(ch, start_az, start_elev) < 0.5f) cost += 20.0f;
            }
            /* A tree within 12 units is in the lens and disqualifying; a few
               within 30 is normal in a forest. Charging the full penalty out
               to 45 made the search prefer treeless ground -- which is bare
               rock and beach, so the camera parked at the foot of the massif
               looking up it. */
            int in_lens = 0;
            for (int ti = 0; ti < tree_count; ti++) {
                float tdx = x - trees[ti].x, tdz = z - trees[ti].z;
                float d2 = tdx * tdx + tdz * tdz;
                if (d2 < 144.0f) { in_lens = 1; break; }
                else if (d2 < 900.0f) cost += 3.0f;
            }
            /* a trunk in the lens is a defect, not a cost: as a penalty the
               search could still buy it when every other candidate looked
               worse, which is how the camera ended up inside a thicket with a
               canopy filling a corner of the frame */
            if (in_lens) continue;
            if (cost < best) { best = cost; bx = x; bz = z; bEye = eye; }
        }
    }
    if (best > 1e8f) return;   /* nothing usable: keep the fixed default */
    cam_x = bx; cam_z = bz; cam_y = bEye;
    float dx = peak_x - cam_x, dz = peak_z - cam_z;
    yaw = tyaw = atan2f(dx, dz);
    float elev = atan2f(peak_y - cam_y, sqrtf(dx * dx + dz * dz));
    /* summit ~12% below the top edge: aim below it by 0.76 of a half frame */
    pitch = tpitch = elev - 0.76f * 0.5f * fovy;
    if (pitch < -0.55f) pitch = tpitch = -0.55f;
    if (pitch > 0.25f) pitch = tpitch = 0.25f;
}

